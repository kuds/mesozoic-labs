def manus_hollow(x, y, z):
    """Indent the middle of the palmar margin behind the metacarpal arch."""
    hollow = max(-x, 0) * math.exp(-((y / 0.049) ** 2))
    return x + 0.68 * hollow, y, z + 0.16 * hollow


def limb_surfaces(mesh):
    surfaces = [mesh(f"{name}_surface", sections) for name, sections in LONG_BONES.items()]
    surfaces.append(mesh("manus_surface", FEET["manus"], point_map=manus_hollow))
    surfaces.append(mesh("pes_surface", FEET["pes"]))
    return surfaces
