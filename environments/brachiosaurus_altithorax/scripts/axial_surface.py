"""Rebuild the inline Brachiosaurus soft-tissue meshes after editing their sections.

Run with `python -m environments.brachiosaurus_altithorax.scripts.axial_surface`.
The renderer rounds the surface through these transverse stations. Lengths are
simulation metres. The simulation uses simple contact and inertia proxies.
"""

import math
from pathlib import Path

from .limb_surface import limb_surfaces

ASSET = Path(__file__).resolve().parents[1] / "anatomical/assets/brachiosaurus_altithorax_anatomical.xml"
START = "    <!-- Start axial surfaces (generated by scripts/axial_surface.py). -->"
END = "    <!-- End axial surfaces. -->"
SIDES = 20

# (x, height of section centre, half-width, half-depth). The ribs expand
# forwards from the sacrum; the withers rise between the shoulder girdles.
TRUNK = [
    (-1.12, 0.025, 0.145, 0.16),
    (-0.99, 0.034, 0.210, 0.224),
    (-0.88, 0.038, 0.246, 0.265),
    (-0.72, 0.035, 0.305, 0.333),
    (-0.49, 0.035, 0.375, 0.385),
    (-0.18, 0.025, 0.405, 0.425),
    (0.15, 0.045, 0.415, 0.465),
    (0.43, 0.09, 0.38, 0.485),
    (0.62, 0.14, 0.33, 0.47),
    (0.77, 0.195, 0.275, 0.435),
    (0.89, 0.265, 0.22, 0.375),
    (1.00, 0.35, 0.162, 0.29),
]

# The nose slopes down from the bony narial arch. USNM 5730 is a tentatively referred
# skull; the holotype does not preserve a skull or neck (Taylor, 2009).
SKULL = [
    (-0.075, 0.005, 0.036, 0.041),
    (-0.04, 0.014, 0.061, 0.062),
    (0.018, 0.02, 0.078, 0.081),
    (0.068, 0.024, 0.078, 0.089),
    (0.105, 0.014, 0.071, 0.078),
    (0.151, -0.003, 0.060, 0.058),
    (0.20, -0.009, 0.054, 0.046),
    (0.239, -0.013, 0.047, 0.038),
    (0.258, -0.013, 0.032, 0.025),
]

# (length in X, rise in Z, width and depth at each end). Segment tips
# overlap the next joint, as the skin spans each underlying articulation.
NECK = [
    (0.38, 0.46, 0.225, 0.25, 0.148, 0.171),
    (0.36, 0.47, 0.148, 0.171, 0.101, 0.119),
    (0.35, 0.375, 0.101, 0.119, 0.073, 0.087),
    (0.33, 0.23, 0.073, 0.087, 0.055, 0.063),
]
TAIL = [
    (-0.52, -0.055, 0.245, 0.27, 0.152, 0.164),
    (-0.53, -0.075, 0.152, 0.164, 0.086, 0.094),
    (-0.50, -0.065, 0.086, 0.094, 0.042, 0.046),
    (-0.49, -0.030, 0.042, 0.046, 0.006, 0.007),
]


def chain_sections(link):
    dx, dz, base_width, base_depth, tip_width, tip_depth = link
    # Section planes are perpendicular to the link. Rounded ends intersect at
    # the actual pivot through the working flexion range without open seams.
    length = math.hypot(dx, dz)
    sections = [
        (-0.85 * base_depth / length, 0.42 * base_width, 0.42 * base_depth),
        (-0.45 * base_depth / length, 0.90 * base_width, 0.90 * base_depth),
        (0.0, base_width, base_depth),
        (0.45, 0.55 * base_width + 0.45 * tip_width, 0.55 * base_depth + 0.45 * tip_depth),
        (1.0, tip_width, tip_depth),
        (1 + 0.4 * tip_depth / length, 0.88 * tip_width, 0.88 * tip_depth),
        (1 + 0.85 * tip_depth / length, 0.42 * tip_width, 0.42 * tip_depth),
    ]
    return [(dx * t, dz * t, w, h) for t, w, h in sections]


def mesh(name, sections, slope=0.0, point_map=None):
    """Write one closed visual surface with smooth normals and outward winding."""
    rows = []
    faces = []
    # Section order must increase forwards when looking down the x axis.
    if sections[0][0] > sections[-1][0]:
        sections = list(reversed(sections))
    for x, z, width, depth in sections:
        points = []
        for side in range(SIDES):
            angle = math.tau * side / SIDES
            offset = depth * math.sin(angle)
            xyz = (x - offset * math.sin(slope), width * math.cos(angle), z + offset * math.cos(slope))
            if point_map is not None:
                xyz = point_map(*xyz)
            points.extend("0" if abs(v) < 0.000005 else f"{v:.5f}".rstrip("0").rstrip(".") for v in xyz)
        rows.append(" ".join(points))
    for ring in range(len(sections) - 1):
        row = []
        for side in range(SIDES):
            a = ring * SIDES + side
            b = ring * SIDES + (side + 1) % SIDES
            # Opposite flanks use reflected diagonals. Splitting every curved
            # quad the same way skews the surface and its compiled inertia axes.
            if (side + SIDES // 4) % SIDES < SIDES // 2:
                row.extend((a, b, a + SIDES, b, b + SIDES, a + SIDES))
            else:
                row.extend((a, b, b + SIDES, a, b + SIDES, a + SIDES))
        faces.append(" ".join(map(str, row)))
    last = (len(sections) - 1) * SIDES
    # Anchor each cap fan on the sagittal plane so its triangles also mirror.
    midline = SIDES // 4
    for side in range(1, SIDES - 1):
        a = (midline + side) % SIDES
        b = (a + 1) % SIDES
        faces.append(f"{midline} {b} {a} {last + midline} {last + a} {last + b}")
    vertices = "\n            ".join(rows)
    triangles = "\n          ".join(faces)
    return f'    <mesh name="{name}" smoothnormal="true"\n        vertex="{vertices}"\n        face="{triangles}"/>'


def rebuild(path=ASSET):
    surfaces = [mesh("thorax_surface", TRUNK), mesh("skull_surface", SKULL)]
    for region, links in (("neck", NECK), ("tail", TAIL)):
        for i, link in enumerate(links, 1):
            dx, dz = link[:2]
            slope = math.atan(dz / dx)
            surfaces.append(mesh(f"{region}_{i}_surface", chain_sections(link), slope))
    surfaces.extend(limb_surfaces(mesh))
    before, body = path.read_text().split(START)
    _, after = body.split(END)
    path.write_text(before + "\n".join([START, *surfaces, END]) + after)


if __name__ == "__main__":
    rebuild()
