TAIL_COLS = ["tail_3_pitch_act_command_mean", "tail_3_pitch_mean_deg", "tail_tip_chord_mean_deg", "saturated_actuator",
             "rail_actuators", "parked_actuators", "screen_v2_reasons"]


def csv_summary(path):
    rows = C.read_csv(path)
    cols = list(rows[0].keys()) if rows else []
    ts = sorted({int(r["timesteps"]) for r in rows}) if rows else []
    pc = [c for c in POSTURE_COLS if c in cols]
    tc = [c for c in TAIL_COLS if c in cols]
    return (f"{len(rows)} rows, {len(ts)} evals {ts[0] if ts else '-'}..{ts[-1] if ts else '-'}; {len(cols)} cols\n"
            f"        posture cols: {', '.join(pc) or 'none'}\n        tail cols: {', '.join(tc) or 'none'}")


def npz_summary(path, keys_of_interest):
    d = np.load(path, allow_pickle=False)
    t = None
    for k in ("timesteps", "update_timesteps", "num_timesteps"):
        if k in d.files:
            t = d[k]
            break
    have = [k for k in keys_of_interest if k in d.files]
    rng = f"{len(t)} rows {int(t[0])}..{int(t[-1])}" if t is not None and len(t) else "?"
    return f"{rng}; {len(d.files)} keys; of interest: {', '.join(have) or 'none'}"


GP_KEYS = ["com_fore_aft_mean_m", "root_pitch_mean_deg", "action_dc_per_actuator", "leg_q_l_r_mean_hip_pitch_deg",
           "term_tail_home_pose", "term_action_saturation"]
PP_KEYS = ["obs_rms_mean", "obs_rms_count", "rollout_mu_mean", "rollout_mu_beyond_high_share",
           "rollout_action_saturated_share", "std_per_actuator"]
DG_KEYS = ["tilt_angle", "head_tip_z", "head_pelvis_rel_z", "pelvis_height", "neck_posture_error", "action_saturation",
           "torso_height"]


def show(label, path, kind):
    if not os.path.exists(path):
        print(f"    {label:22s} ABSENT locally ({path})")
        return
    sz = os.path.getsize(path)
    if kind == "csv":
        s = csv_summary(path)
    elif kind == "gp":
        s = npz_summary(path, GP_KEYS)
    elif kind == "pp":
        s = npz_summary(path, PP_KEYS)
    elif kind == "dg":
        s = npz_summary(path, DG_KEYS)
    elif kind == "ev":
        s = npz_summary(path, ["results"])
    else:
        s = ""
    print(f"    {label:22s} {sz:>10,d} B  {s}")


