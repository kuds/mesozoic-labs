#: The frame-weighted values ``passive_over_time`` keeps beside the ones over time.
PASSIVE_TWINS = ("rms_id_frames_nm", "rms_total_frames_nm", "cont_ratio_id_frames", "cont_ratio_total_frames")


def test_passive_loads_over_time():
    """``passive_over_time``: the torque RMS values and the sustained ratios of ``screen.passive_loads``' block
    weighted by each frame's duration, the frame-weighted ones beside them; on uniform frames the block's own
    numbers."""
    K = 120
    rng = np.random.default_rng(5)
    tau, omega = rng.normal(0, 2.0, (K, len(NAMES))), rng.normal(0, 1.0, (K, len(NAMES)))
    M = SimpleNamespace(names=list(NAMES))
    base = {}
    for grp, jn, b, f in (("neck", "neck_pitch", 0.05, 0.02), ("tail", "tail_yaw", 0.1, 0.03)):
        i = NAMES.index(jn)
        tot = tau[:, i] + b * omega[:, i] + f * np.sign(omega[:, i])
        rid, rtot = float(np.sqrt(np.mean(tau[:, i] ** 2))), float(np.sqrt(np.mean(tot**2)))
        base[grp] = dict(joint=jn, damping=b, frictionloss=f, sustained_nm=4.0, rms_id_nm=rid, rms_total_nm=rtot,
                         rms_passive_alone_nm=1.0, cont_ratio_id=rid / 4.0, cont_ratio_total=rtot / 4.0,
                         rms_total_over_id=rtot / rid, peak_ratio_total=0.9, speed_rms_rad_s=1.0)
    t = np.cumsum(rng.uniform(0.004, 0.008, K))
    w = np.gradient(t)
    out = setscreen.passive_over_time(M, base, tau, omega, t)
    for grp, p in out.items():
        i = NAMES.index(p["joint"])
        pas = p["damping"] * omega[:, i] + p["frictionloss"] * np.sign(omega[:, i])
        rid = math.sqrt(np.sum(w * tau[:, i] ** 2) / np.sum(w))
        rtot = math.sqrt(np.sum(w * (tau[:, i] + pas) ** 2) / np.sum(w))
        assert p["rms_id_nm"] == pytest.approx(rid, rel=1e-13) and p["rms_total_nm"] == pytest.approx(rtot, rel=1e-13)
        assert p["rms_passive_alone_nm"] == pytest.approx(math.sqrt(np.sum(w * pas**2) / np.sum(w)), rel=1e-13)
        assert p["cont_ratio_id"] == pytest.approx(rid / 4.0, rel=1e-13) and p["cont_ratio_total"] == pytest.approx(rtot / 4.0, rel=1e-13)
        assert p["rms_total_over_id"] == pytest.approx(rtot / rid, rel=1e-13)
        b0 = base[grp]
        assert (p["rms_id_frames_nm"], p["rms_total_frames_nm"], p["cont_ratio_id_frames"], p["cont_ratio_total_frames"]) == (
            b0["rms_id_nm"], b0["rms_total_nm"], b0["cont_ratio_id"], b0["cont_ratio_total"])
        assert p["cont_ratio_total"] != b0["cont_ratio_total"] and p["peak_ratio_total"] == 0.9 and p["speed_rms_rad_s"] == 1.0
    assert base["neck"]["rms_id_nm"] == float(np.sqrt(np.mean(tau[:, NAMES.index("neck_pitch")] ** 2)))  # the input is kept
    same = setscreen.passive_over_time(M, base, tau, omega, 0.007 * np.arange(K))
    for grp, p in same.items():
        assert {k: v for k, v in p.items() if k not in PASSIVE_TWINS} == base[grp] and set(p) == set(base[grp]) | set(PASSIVE_TWINS)
        assert p["cont_ratio_total_frames"] == p["cont_ratio_total"] and p["rms_id_frames_nm"] == p["rms_id_nm"]


