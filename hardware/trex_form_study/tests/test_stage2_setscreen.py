@needs_look
def test_v0_walks_generated_in_a_temporary_directory_screen_to_the_ladders_blocks(src, tmp_path):
    """The two V0 walks of a set (``sizing.NOMINAL`` and ``look.speed_spec(H)``) generated here: their look-format
    files hash to the ladder's V0 rungs and their blocks are the committed rung blocks; nothing under
    ``stage2/look`` is touched."""
    entries, rungs = ladder_docs()
    d = tmp_path / "V0" / BODY
    before = {p: p.stat().st_mtime_ns for p in sorted(LOOK.rglob("*")) if p.is_file()}
    for name, spec in (("nominal", sizing.NOMINAL), ("v0.4", look.speed_spec(src["H"]))):
        ladder_entry, rung = entries[LADDER[name]]["V0"], rungs[LADDER[name]]["V0"]
        entry = look_entry(src, d, name, spec)
        assert entry["sha256"] == ladder_entry["sha256"] == s2io.sha256_file(d / "look" / f"{name}.npz")
        for key in ("spec", "info", "measured", "price", "flags", "frames", "ik_ok", "ik_fail_frames"):
            assert entry[key] == ladder_entry[key], key
        block = setscreen.screen_walk(src, d, name, entry)
        check_walk_block(block, name, "V0", entry, rung)
        assert block["arrays"]["file"] == f"look/{name}.npz"
    assert {p: p.stat().st_mtime_ns for p in sorted(LOOK.rglob("*")) if p.is_file()} == before


@built
def test_built_v0_set_blocks_equal_the_look_ladders():
    """The built ``V0`` set: its ``nominal`` and ``v0.4`` blocks are the look ladder's V0 rung blocks; every
    available reference has a block of its own file; ``SCREEN.md`` regenerates byte for byte; no wall time."""
    docs = setio.load(V0_SET)
    doc = docs["screen.json"]
    if doc is None:
        pytest.skip("the V0 set is not screened yet (python -m designlab.stage2.setscreen run --set V0 --body 75-M-H-10)")
    entries, rungs = ladder_docs()
    for name, speed in LADDER.items():
        block = doc["blocks"][name]
        assert setscreen.ladder_differences(block, rungs[speed]["V0"]) == [], name
        assert block["arrays"]["sha256"] == entries[speed]["V0"]["sha256"] == docs["set.json"]["look_entries"][name]["sha256"]
        assert block["range"]["joints"] == docs["set.json"]["look_entries"][name]["price"]["clearance"]["joint_range_margins"]
    st = setscreen.status("V0", BODY)
    assert st["missing"] == [] and st["stale"] == [] and st["extra"] == [] and sorted(st["current"]) == sorted(doc["blocks"])
    for name, block in doc["blocks"].items():
        assert set(block["verdict"]) == {"text", "within_limits", "over", "near", "a1_over", "blocks_freeze"}, name
        assert block["verdict"]["a1_over"] is any(block["drives"][g][k] > 1.0 for g in ("neck", "tail") for k in setscreen.KINDS)
    assert doc["a1_over"] == [n for n, b in doc["blocks"].items() if b["verdict"]["a1_over"]]
    assert doc["blocks_freeze"] == {n: b["verdict"]["blocks_freeze"] for n, b in doc["blocks"].items() if b["verdict"]["blocks_freeze"]}
    assert no_wall_time(doc)
    assert (V0_SET / "SCREEN.md").read_text() == setscreen.markdown(doc)
