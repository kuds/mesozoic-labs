def write_tiny_set(root: Path) -> Path:
    """``<root>/T/<body>/``: two walks, four moves and one item with no reference; no array is read by the stand-ins."""
    d = root / "T" / BODY
    d.mkdir(parents=True)
    walks = ("nominal", "v0.4")
    refs = {w: dict(name=w, file=f"refs/{w}.npz", sha256=sha(f"ref {w}"), look_file=f"look/{w}.npz",
                    look_sha256=sha(f"look {w}"), frames=160) for w in walks}

    def move(name, kind, a, b, builder, causal=False, **more):
        return dict(name=name, kind=kind, from_=a, to=b, file=f"transitions/{name}.npz", sha256=sha(f"move {name}"),
                    split="statics", ik_ok=True, move=dict(kind=more.pop("move_kind", kind), builder=builder, causal=causal),
                    a1_over=None, **more)

    trans = {
        "start": move("start", "start", "stand", "nominal", "start"),
        "nominal_to_v0.4": move("nominal_to_v0.4", "walk", "nominal", "v0.4", "change"),
        "stop2_v0.4": move("stop2_v0.4", "stop", "v0.4", "stand", "stop_two_step", causal=True),
        "turn90_pi4_left": move("turn90_pi4_left", "walk", "v0.4", "v0.4", "turn", causal=True, move_kind="turn",
                                turn=dict(angle_rad=math.pi / 2, rate_rad_s=math.pi / 4, direction="left")),
        "turn90_1_left": dict(name="turn90_1_left", kind="turn", available=False,
                              reason="no stride factor of the grid passes the kinematic thigh-twist rule (0.85)"),
    }
    s2io.write_json(d / "refs.json", dict(body=BODY, set="T", references=refs))
    s2io.write_json(d / "transitions.json", dict(body=BODY, set="T", transitions=trans))
    s2io.write_json(d / "set.json", dict(set="T", body=BODY, freezes=[], look_entries={
        w: dict(file=f"look/{w}.npz", sha256=refs[w]["look_sha256"], frames=160) for w in walks}))
    return d


