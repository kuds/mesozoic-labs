    base = setscreen.drive_flags(src, arrs["tau"][a:b], arrs["omega"][a:b])
    assert not base["a1_over"] and base["over"] == []
    i = list(arrs["joints"]).index("tail_yaw")
    k = 1.2 / base["drives"]["tail"]["peak_ratio"]

    def heavy_tail(a):
        a["tau"] = a["tau"].copy()
        a["tau"][:, i] *= k

    d, entry = cut_move(tmp_path, name, "turn_tail", a, b, edit=heavy_tail, **TURN_ENTRY)
    block = setscreen.screen_move(src, d, "turn_tail", entry, None)
    assert block["drives"]["tail"]["peak_ratio"] == pytest.approx(1.2, rel=1e-12)
    v = block["verdict"]
    assert v["a1_over"] is True and v["within_limits"] is False and v["blocks_freeze"] == []
    assert [o["limit"] for o in v["over"]] == ["tail peak"] + (["tail cont"] if block["drives"]["tail"]["cont_ratio"] > 1 else [])
    assert "does not block the freeze; a1_over" in v["text"]
    assert block["range"]["ok"] is True and 0.5 < block["range"]["hip_yaw_range_use"] < 0.65  # Stage 1's 0.58
    assert block["recheck"]["equal_to_recorded"] is False and block["recheck"]["tau_max_abs_diff_nm"] > 0.05
    with np.load(d / entry["file"]) as z:
        fl = setscreen.drive_flags(src, z["tau"], z["omega"])
        as_change_range = setscreen.move_range(src, z["q"], "change", entry, block["range"]["joints"])
    assert fl["a1_over"] and not fl["over_leg_drive"] and fl["over"] == v["over"]
    assert as_change_range["ok"] is True
    as_change = setscreen.judge_move("change", False, fl, True, 0, block["contact"], block["clearance"], as_change_range,
                                     block["accel"])
    assert as_change["a1_over"] and as_change["blocks_freeze"] == v["over"]


