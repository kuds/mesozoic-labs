def test_a_window_that_begins_inside_a_swing_is_refused():
    """The clearance screen reads the middle half of each swing run: of a swing cut by the file's first frame that
    is not the swing's middle half.  A swing on the first frame must begin there (``swing_u`` 0)."""
    sw = np.zeros((40, 2), bool)
    sw[:6, 1] = sw[20:30, 0] = True
    u = np.full((40, 2), np.nan)
    u[:6, 1] = 0.3125 + np.arange(6) * 0.125  # the first frame is 0.3125 of the way through the right foot's swing
    with pytest.raises(setscreen.Refused, match="m: the right foot is 0.3125 of the way through a swing on the file's "
                                                "first frame"):
        setscreen.check_swing_window("m", sw, u)
    u[:6, 1] = (1 + np.arange(6)) / 7.0  # cut by one frame
    with pytest.raises(setscreen.Refused, match="of the way through a swing on the file's first frame"):
        setscreen.check_swing_window("m", sw, u)
    u[:6, 1] = np.arange(6) / 6.0
