NAMES = [f"{s}_{j}" for s in statics.SIDES for j in ("hip_roll", "hip_pitch", "hip_yaw", "knee", "ankle_pitch", "ankle_roll")] \
    + ["neck_pitch", "tail_yaw"]


def fake_src(layout="tandem", sustained=5.0) -> dict:
    """A body for ``drive_flags`` with no model: 14 drives of one actuator each (sustained 5 N m, planning peak 20 N m,
    8 rad/s at the bus)."""
    def act(g):
        return SimpleNamespace(id=f"act_{g}", sustained=sustained, peak=20.0, box=None, speed_at=lambda bus: 8.0)

    return dict(M=SimpleNamespace(names=list(NAMES)), design=SimpleNamespace(act=act), layout=layout,
                record=dict(selection=dict(bus=24.0)))


def series(K=240, seed=3) -> tuple:
    rng = np.random.default_rng(seed)
    return rng.normal(0.0, 3.0, (K, len(NAMES))), rng.normal(0.0, 1.5, (K, len(NAMES)))


def by_hand(tau, w, layout) -> dict:
    """Each group's RMS over time from the per-joint columns: sqrt(sum_k w_k x_k^2 / sum_k w_k) over both sides."""
    col = {n: tau[:, i] for i, n in enumerate(NAMES)}

    def rms(*cols):
        return float(np.sqrt(sum(np.sum(w * c**2) for c in cols) / (len(cols) * np.sum(w))))

    out = {g: rms(col[f"left_{j}"], col[f"right_{j}"]) for g, j in sizing.JOINT_OF.items()}
    a, b = [], []
    for s in statics.SIDES:
        tp, tr = col[f"{s}_ankle_pitch"], col[f"{s}_ankle_roll"]
        a.append(0.5 * (tp + tr) if layout == "tandem" else tp)
        b.append(0.5 * (tp - tr) if layout == "tandem" else tr)
    return out | dict(ankle_a=rms(*a), ankle_b=rms(*b), neck=rms(col["neck_pitch"]), tail=rms(col["tail_yaw"]))


@pytest.mark.parametrize("layout", ["tandem", "serial"])
def test_a_moves_sustained_ratio_is_its_rms_over_time(layout):
    """``drive_flags``: on frames that are not uniform in time each frame is weighted by its duration; the
    frame-weighted value (``envelope._ratios``' own) is kept beside it; peak and speed ratios need no weight."""
    src = fake_src(layout)
    tau, omega = series()
    K = len(tau)
    # the second half of the file at 0.7 of the first half's frame interval (a turn's quicker strides)
    t = np.concatenate([[0.0], np.cumsum(np.r_[np.full(K // 2, 0.007), np.full(K - K // 2 - 1, 0.0049)])])
    w, uniform = setscreen.frame_weights(t)
    assert not uniform and np.array_equal(w, np.gradient(t)) and w.sum() == pytest.approx(t[-1] - t[0] + 0.5 * (0.007 + 0.0049))
    assert (w[0], w[K // 2], w[-1]) == (pytest.approx(0.007), pytest.approx(0.5 * (0.007 + 0.0049)), pytest.approx(0.0049))
    want = envelope._ratios(src["design"], 24.0, sizing._motor_space(NAMES, tau, omega, layout))
    fl = setscreen.drive_flags(src, tau, omega, t)
    hand = by_hand(tau, w, layout)
    assert fl["frames_uniform"] is False and list(fl["drives"]) == list(want)
    for g, d in fl["drives"].items():
        assert d["rms"] == pytest.approx(hand[g], rel=1e-13) and d["cont_ratio"] == pytest.approx(hand[g] / 5.0, rel=1e-13)
        assert (d["rms_frames"], d["cont_ratio_frames"]) == (want[g]["rms"], want[g]["cont_ratio"])
        assert d["rms"] != d["rms_frames"]
        assert (d["peak"], d["speed"], d["peak_ratio"], d["speed_ratio"], d["actuator"]) == (
            want[g]["peak"], want[g]["speed"], want[g]["peak_ratio"], want[g]["speed_ratio"], want[g]["actuator"])
        assert d["worst"] == max(d["cont_ratio"], d["peak_ratio"], d["speed_ratio"])
        assert set(d) == set(want[g]) | {"rms_frames", "cont_ratio_frames"}
    # the frame of each stacked sample is read from sizing._motor_space itself, whatever the ankle layout
    frame_of = setscreen._frame_of(NAMES, K)
    assert np.array_equal(frame_of["knee"], np.repeat(np.arange(K), 2)) and np.array_equal(frame_of["tail"], np.arange(K))
    assert np.array_equal(frame_of["ankle_a"], np.tile(np.arange(K), 2)) and set(frame_of) == set(want)
    # frames uniform in time: one number, envelope._ratios' own, bit for bit (nothing is computed twice)
    tu = 0.3 + 0.0070977 * np.arange(K)
    assert setscreen.frame_weights(tu)[1] is True and np.ptp(np.diff(tu)) > 0.0  # uniform to rounding, not to the bit
    fu = setscreen.drive_flags(src, tau, omega, tu)
    assert fu["frames_uniform"] is True
    for g, d in fu["drives"].items():
        assert {k: v for k, v in d.items() if not k.endswith("_frames")} == s2io.plain(want[g])
        assert (d["rms_frames"], d["cont_ratio_frames"]) == (d["rms"], d["cont_ratio"])
        assert setscreen.rms_over_time(sizing._motor_space(NAMES, tau, omega, layout)[g][0],
                                       setscreen.frame_weights(tu)[0][frame_of[g]]) == pytest.approx(d["rms"], rel=1e-13)
    assert fu["governing"] == s2io.plain(screen.governing(want))


