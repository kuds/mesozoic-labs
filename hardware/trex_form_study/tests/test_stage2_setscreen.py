def test_a_window_that_ends_inside_a_swing_is_refused():
    sw = np.zeros((40, 2), bool)
    sw[5:15, 0] = sw[22:33, 1] = True
    setscreen.check_swing_window("m", sw)  # every swing whole
    assert setscreen.support_phases(sw)[4:6] == [("left", "right"), ("right",)]
    assert setscreen.support_phases(sw)[25] == ("left",)
    first = sw.copy()
    first[:5, 0] = True  # a swing that begins with the file (a causal move starts at a lift-off) is whole
    setscreen.check_swing_window("m", first)
    cut = sw.copy()
    cut[33:, 1] = True
    with pytest.raises(setscreen.Refused, match="right foot is in swing on the file's last frame;"):
        setscreen.check_swing_window("m", cut)
    both = first.copy()
    both[35:, 0] = True  # the cyclic runs of clearance._swing_runs would join the two parts into one swing
    assert len(clearance._swing_runs(setscreen.support_phases(both), "left")) == 1
    with pytest.raises(setscreen.Refused, match="left foot is in swing on the file's last frame and on its first"):
        setscreen.check_swing_window("m", both)
    assert issubclass(setscreen.Refused, s2io.S2Error)


def known_path(n=900, T=0.9, v=0.3, a=0.004, b=0.012, c=0.003, turn=0.0, seed=1):
    """Frames at uneven times of a CoM path with a known acceleration, along a heading that turns at ``turn`` rad/s."""
    rng = np.random.default_rng(seed)
    t = np.cumsum(rng.uniform(0.004, 0.008, n))
    t -= t[0]
    w = 2 * np.pi / T
    hd = turn * t
    s, lat = v * t + a * np.sin(w * t), b * np.sin(w * t)
    if turn:
        path = np.column_stack([v / turn * np.sin(hd), v / turn * (1 - np.cos(hd))])
    else:
        path = np.column_stack([v * t, np.zeros(n)])
    com_xy = path + np.column_stack([a * np.sin(w * t) * np.cos(hd) - lat * np.sin(hd),
                                     a * np.sin(w * t) * np.sin(hd) + lat * np.cos(hd)])
    com = np.column_stack([com_xy, 0.4 + c * np.sin(2 * w * t)])
    return dict(t=t, com=com, heading=hd, path=path, phase=t / T, w=w, s=s)


def test_accelerations_of_a_known_move():
    """Second differences on uneven frames with no wrap; the 1 Hz reading is ``readings.reference_readings``' own."""
    p = known_path()
    n, w = len(p["t"]), p["w"]
    feet = np.zeros((n, 2, 3))
    feet[:, 0, 2] = 0.02 * np.sin(w * p["t"]) ** 2
    acc = setscreen.move_accelerations(p["t"], p["com"], p["heading"], feet)
    assert acc["com_forward_peak"] == pytest.approx(0.004 * w * w, rel=2e-3)
    assert acc["com_lateral_peak"] == pytest.approx(0.012 * w * w, rel=2e-3)
    assert acc["com_horizontal_peak"] == pytest.approx(math.hypot(0.004, 0.012) * w * w, rel=2e-3)
    assert acc["com_vertical_max"] == pytest.approx(0.003 * 4 * w * w, rel=2e-3)
    assert acc["com_vertical_min"] == pytest.approx(-0.003 * 4 * w * w, rel=2e-3)
    assert acc["foot_vertical_peak"] == pytest.approx(0.02 * 2 * w * w, rel=2e-3)
    assert acc["spec_start_stop"] == 1.5 and acc["resample_hz"] == 500.0
    ref = readings.reference_readings(dict(t=p["t"], com=p["com"], heading=p["heading"]), "start")
    assert acc["com_forward_lp1hz_peak"] == ref["accel_forward_lp1hz_peak_m_s2"]  # the same operations, bit for bit
    assert acc["com_forward_lp1hz_peak"] < 0.9 * acc["com_forward_peak"]  # 1.1 Hz through the 1 Hz filter
    # the second difference is exact for a quadratic on any grid, and reads nothing across the file's ends
    t = p["t"]
    quad = np.column_stack([0.5 * 1.2 * t * t, -0.5 * 0.7 * t * t, 0.4 + 0 * t])
    acc = setscreen.move_accelerations(t, quad, np.zeros(n), np.zeros((n, 2, 3)))
    assert acc["com_forward_peak"] == pytest.approx(1.2, rel=1e-9) and acc["com_lateral_peak"] == pytest.approx(0.7, rel=1e-9)
    assert acc["com_horizontal_peak"] == pytest.approx(math.hypot(1.2, 0.7), rel=1e-9)
    assert abs(acc["com_vertical_max"]) < 1e-9 and acc["foot_vertical_peak"] == 0.0
    # along the heading: a centripetal acceleration v w is across a turning heading, not along it
    c = known_path(a=0.0, b=0.0, c=0.0, turn=0.5)
    acc = setscreen.move_accelerations(c["t"], c["com"], c["heading"], np.zeros((n, 2, 3)))
    assert acc["com_lateral_peak"] == pytest.approx(0.3 * 0.5, rel=1e-3) and acc["com_forward_peak"] < 1e-3
    # a speed change of 0.2 m/s in 0.1 s: the 1 Hz reading stays under the raw peak (decision 10's filter)
    tt = np.linspace(0, 6, 1201)
    vel = np.interp(tt, [0, 3, 3.1, 6], [0.2, 0.2, 0.4, 0.4])
    x = np.concatenate([[0.0], np.cumsum(0.5 * (vel[1:] + vel[:-1]) * np.diff(tt))])
    lp = setscreen.forward_acceleration_lp(tt, np.column_stack([x, 0 * x]), 0 * x)
    assert 0.3 < np.max(np.abs(lp)) < 0.2 * 2.3 and len(lp) == len(np.arange(0, 6, 1 / 500.0))


def test_sway_per_stride_in_the_path_frame():
    H = 0.5
    p = known_path()
    s = setscreen.move_sway(p["t"], p["phase"], p["com"], p["path"], p["heading"], H)
