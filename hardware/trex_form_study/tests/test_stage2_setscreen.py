def look_entry(src, d: Path, name: str, spec) -> dict:
    """A walk generated into ``d/look/<name>.npz`` with its entry of ``look.write``'s shape less the wall times, as
    a set's builder makes it; through JSON, as ``set.json`` holds it."""
    with s2io.r2():
        g = look.generate(src, spec)
        arrs = look.arrays(src, g)
        info = g["info"]
        sha256 = s2io.write_npz(d / "look" / f"{name}.npz", arrs)
        rolls = {s: [dict(r) for r in g["look"]["rolls"][s] if 0 <= r["t_lift_off"] < info["window_s"]] for s in statics.SIDES}
        m = look._plain(look.measure(arrs, info, src["H"], crouch=spec.crouch))
        pr = look._plain(look.price(src, arrs, info))
    entry = dict(body=src["body"], speed=name, variant=d.parent.name, features=[], file=f"look/{name}.npz", sha256=sha256,
                 frames=len(g["q"]), spec=look._plain(asdict(spec)), info=look._plain({k: v for k, v in info.items() if k != "look"}),
                 ik_ok=bool(g["ik_ok"]), ik_fail_frames=len(g["ik_fail_frames"]),
                 zmp_error_final_mm=1e3 * info["zmp_error_history_m"][-1], zmp_margin_min_mm=1e3 * info["zmp_margin_min_m"],
                 rolls=look._plain(rolls), measured=m, price=pr, flags=look.flags(spec, info, m, pr, rolls))
    return json.loads(json.dumps(entry))


@slow
@needs_look
def test_v0_walks_generated_in_a_temporary_directory_screen_to_the_ladders_blocks(src, tmp_path):
    """The two V0 walks of a set (``sizing.NOMINAL`` and ``look.speed_spec(H)``) generated here: their look-format
    files hash to the ladder's V0 rungs and their blocks are the committed rung blocks, from ``screen_walk`` and
    through ``run`` (which adds the file the bar plays); nothing under ``stage2/look`` is touched."""
    entries, rungs = ladder_docs()
    d = tmp_path / "V0" / BODY
    before = {p: p.stat().st_mtime_ns for p in sorted(LOOK.rglob("*")) if p.is_file()}
    look_entries, refs, blocks = {}, {}, {}
    for name, spec in (("nominal", sizing.NOMINAL), ("v0.4", look.speed_spec(src["H"]))):
        ladder_entry, rung = entries[LADDER[name]]["V0"], rungs[LADDER[name]]["V0"]
        entry = look_entry(src, d, name, spec)
        assert entry["sha256"] == ladder_entry["sha256"] == s2io.sha256_file(d / "look" / f"{name}.npz")
        for key in ("spec", "info", "measured", "price", "flags", "frames", "ik_ok", "ik_fail_frames"):
            assert entry[key] == ladder_entry[key], key
        block = setscreen.screen_walk(src, d, name, entry)
        check_walk_block(block, name, "V0", entry, rung)
        assert block["arrays"]["file"] == f"look/{name}.npz" and block["reference"] is None
        # the walk's Stage 1-format file, which a set's builder writes beside the look-format one (a stand-in here:
        # the screen reads its hash and nothing else of it)
        sha256 = s2io.write_npz(d / "refs" / f"{name}.npz", dict(walk=np.array(name)))
        refs[name] = dict(name=name, file=f"refs/{name}.npz", sha256=sha256, look_file=f"look/{name}.npz",
                          look_sha256=entry["sha256"], frames=entry["frames"])
        look_entries[name], blocks[name] = entry, block
    s2io.write_json(d / "refs.json", dict(body=BODY, set="V0", references=refs))
    s2io.write_json(d / "transitions.json", dict(body=BODY, set="V0", transitions={}))
    s2io.write_json(d / "set.json", dict(set="V0", body=BODY, look_entries=look_entries, freezes=[]))
    res = setscreen.run("V0", BODY, root=tmp_path, procs=0, log=lambda line: None)
    assert res["ran"] == ["nominal", "v0.4"] and res["refused"] == {}
    for name, block in blocks.items():
        got = res["doc"]["blocks"][name]
        assert got == block | dict(reference=dict(file=f"refs/{name}.npz", sha256=refs[name]["sha256"]))
        assert setscreen.ladder_differences(got, rungs[LADDER[name]]["V0"]) == []
    assert setscreen.status("V0", BODY, tmp_path)["current"] == ["nominal", "v0.4"] and no_wall_time(res["doc"])
    assert {p: p.stat().st_mtime_ns for p in sorted(LOOK.rglob("*")) if p.is_file()} == before


