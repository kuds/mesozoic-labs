def look_entry(src, d: Path, name: str, spec) -> dict:
    """A walk generated into ``d/look/<name>.npz`` with its entry of ``look.write``'s shape less the wall times, as
    a set's builder makes it; through JSON, as ``set.json`` holds it."""
    with s2io.r2():
        g = look.generate(src, spec)
        arrs = look.arrays(src, g)
        info = g["info"]
        sha256 = s2io.write_npz(d / "look" / f"{name}.npz", arrs)
        rolls = {s: [dict(r) for r in g["look"]["rolls"][s] if 0 <= r["t_lift_off"] < info["window_s"]] for s in statics.SIDES}
        m = look._plain(look.measure(arrs, info, src["H"], crouch=spec.crouch))
        pr = look._plain(look.price(src, arrs, info))
    entry = dict(body=src["body"], speed=name, variant=d.parent.name, features=[], file=f"look/{name}.npz", sha256=sha256,
                 frames=len(g["q"]), spec=look._plain(asdict(spec)), info=look._plain({k: v for k, v in info.items() if k != "look"}),
                 ik_ok=bool(g["ik_ok"]), ik_fail_frames=len(g["ik_fail_frames"]),
                 zmp_error_final_mm=1e3 * info["zmp_error_history_m"][-1], zmp_margin_min_mm=1e3 * info["zmp_margin_min_m"],
                 rolls=look._plain(rolls), measured=m, price=pr, flags=look.flags(spec, info, m, pr, rolls))
    return json.loads(json.dumps(entry))


