    assert setscreen._tightest(m, leave_out=("_hip_yaw",)) == ["left_hip_roll", "max", 0.1689]
    ok = setscreen.walk_range({k: v for k, v in m.items() if "yaw" not in k})
    assert ok["ok"] is True and ok["tightest"] == ["left_hip_roll", "max", 0.1689] and ok["hip_yaw_range_use"] is None
