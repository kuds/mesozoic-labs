def fake_block(name: str, kind: str, sha256: str, walk: dict | None = None, **over) -> dict:
    """A block with every key ``run`` and ``markdown`` read (``test_real_blocks_have_the_stand_ins_keys``)."""
    drives = {g: dict(actuator=f"act_{g}", rms=0.1, peak=0.2, speed=0.3, cont_ratio=0.5, peak_ratio=0.6,
                      speed_ratio=0.7, worst=0.7) for g in sizing.GROUPS}
    b = dict(body=BODY, name=name, kind=kind, arrays=dict(file=f"x/{name}.npz", sha256=sha256, frames=160),
             drives=drives, governing=["knee", "speed", 0.7],
             passive={g: dict(cont_ratio_total=0.7, peak_ratio_total=0.8) for g in ("neck", "tail")},
             contact=dict(single_support_cop_margin_min_mm=45.07, cop_rule_mm=-10.0, friction_ratio_max=0.34),
             friction=dict(single_support=dict(mu_req_max=0.364), double_support=dict(min_mu_max=0.198),
                           grips={"0.9": True, "0.54": True}),
             sway=dict(com_pp_per_stride_max_H=0.198), accel=dict(com_forward_lp1hz_peak=0.383, com_horizontal_peak=2.16),
             clearance=dict(mid_swing_min_frac_H=0.05), range=dict(tightest=["left_hip_roll", "max", 0.1272],
                                                                   hip_yaw_range_use=0.0),
             over=[], near=[], over_with_passive=[], near_with_passive=[], within_limits=True,
             verdict=dict(text="within the Stage 0 limits", within_limits=True, over=[], near=[], a1_over=False,
                          blocks_freeze=[]))
    if kind == "walk":
        b.update(speed=name, variant="T", reprice=dict(equal_to_recorded=True))
    else:
        b.update(recheck=dict(equal_to_recorded=True),
                 vs_walk=None if walk is None else dict(walk=dict(name=walk["name"], sha256=walk["arrays"]["sha256"]),
                                                        headlines={}))
    for path, value in over.items():
        node = b
        *head, last = path.split("__")
        for key in head:
            node = node[key]
        node[last] = value
    return b


def write_tiny_set(root: Path) -> Path:
    """``<root>/T/<body>/``: two walks, four moves and one item with no reference; no array is read by the stand-ins."""
    d = root / "T" / BODY
    d.mkdir(parents=True)
    walks = ("nominal", "v0.4")
    refs = {w: dict(name=w, file=f"refs/{w}.npz", sha256=sha(f"ref {w}"), look_file=f"look/{w}.npz",
                    look_sha256=sha(f"look {w}"), frames=160) for w in walks}

    def move(name, kind, a, b, builder, causal=False, **more):
        return dict(name=name, kind=kind, from_=a, to=b, file=f"transitions/{name}.npz", sha256=sha(f"move {name}"),
                    split="statics", ik_ok=True, move=dict(kind=more.pop("move_kind", kind), builder=builder, causal=causal),
                    a1_over=None, **more)

    trans = {
        "start": move("start", "start", "stand", "nominal", "start"),
        "nominal_to_v0.4": move("nominal_to_v0.4", "walk", "nominal", "v0.4", "change"),
        "stop2_v0.4": move("stop2_v0.4", "stop", "v0.4", "stand", "stop_two_step", causal=True),
        "turn90_pi4_left": move("turn90_pi4_left", "walk", "v0.4", "v0.4", "turn", causal=True, move_kind="turn",
                                turn=dict(angle_rad=math.pi / 2, rate_rad_s=math.pi / 4, direction="left")),
        "turn90_1_left": dict(name="turn90_1_left", kind="turn", available=False,
                              reason="no stride factor of the grid passes the kinematic thigh-twist rule (0.85)"),
    }
    s2io.write_json(d / "refs.json", dict(body=BODY, set="T", references=refs))
    s2io.write_json(d / "transitions.json", dict(body=BODY, set="T", transitions=trans))
    s2io.write_json(d / "set.json", dict(set="T", body=BODY, freezes=[], look_entries={
        w: dict(file=f"look/{w}.npz", sha256=refs[w]["look_sha256"], frames=160) for w in walks}))
    return d


WALKS = ["nominal", "v0.4"]
