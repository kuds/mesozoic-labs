def ladder_docs() -> tuple[dict, dict]:
    return (json.loads((LOOK / "look_refs.json").read_text())["bodies"][BODY],
            json.loads((LOOK / "screen.json").read_text())["rungs"][BODY])


def check_walk_block(block: dict, name: str, set_name: str, entry: dict, rung: dict) -> None:
    assert setscreen.ladder_differences(block, rung) == []
    assert (block["name"], block["kind"], block["speed"], block["variant"]) == (name, "walk", name, set_name)
    assert set(block) == (set(rung) - {"seconds", "vs_V0"}) | {"name", "kind", "range"}
    assert no_wall_time(block) and json.loads(json.dumps(block, allow_nan=False)) == block
    assert block["arrays"]["sha256"] == entry["sha256"] == rung["arrays"]["sha256"]
    assert block["reprice"] == dict(max_abs_diff=0.0, other_differences=[], equal_to_recorded=True)
    # the headline numbers against V0 itself are the ladder's (V0 against V0)
    assert screen.changes(block, block) == rung["vs_V0"]
    # the range block is the price's joint_range_margins, which screen_rung leaves out
    margins = entry["price"]["clearance"]["joint_range_margins"]
    rng = block["range"]
    assert rng["joints"] == margins and "joint_range_margins" not in block["clearance"]
    gated = clearance.gated_margins(margins)
    assert rng["tightest"] == list(min(gated, key=lambda x: x[2])) and rng["tightest"][2] == block["clearance"]["tightest_joint"][1]
    assert rng["ok"] is block["clearance"]["gates"]["joint_range_margin"] is True and rng["rule_rad"] == 0.10
    assert rng["hip_yaw_range_use"] == 0.0
    v = block["verdict"]
    assert v == dict(text=rung["verdict"], within_limits=True, over=[], near=block["near"], a1_over=False, blocks_freeze=[])


