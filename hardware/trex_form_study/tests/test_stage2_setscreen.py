def cut_move(tmp: Path, src_name: str, name: str, a: int, b: int, edit=None, **entry_over) -> tuple[Path, dict]:
    """Frames ``a:b`` of a Stage 1 transition as a move of its own in ``tmp`` (a set directory), with an entry whose
    recorded numbers are the cut's own.  ``edit(arrays)`` changes the arrays before they are written."""
    arrs = arrays_of(src_name)
    K = len(arrs["q"])
    out = {k: (v[a:b] if v.ndim >= 1 and len(v) == K else v) for k, v in arrs.items()}
    out["t"] = out["t"] - out["t"][0]
    if edit is not None:
        edit(out)
    entry = json.loads((RUN / "transitions.json").read_text())["transitions"][src_name]
    single = out["swing"].sum(axis=1) == 1
    file = f"transitions/{name}.npz"
    sha256 = s2io.write_npz(tmp / file, out)
    entry.update(name=name, file=file, sha256=sha256, frames=len(out["q"]), duration_s=float(out["t"][-1]),
                 min_cop_margin_single_m=float(np.nanmin(out["cop_margin"][single])),
                 max_friction_ratio=float(np.max(out["friction"])))
    entry.update(entry_over)
    return tmp, entry


def lower_lift(src, arrs: dict, scale: float) -> None:
    """Every swing foot's height above the floor scaled by ``scale`` (by the legs' IK; the rest of the pose kept)."""
    M = src["M"]
    feet = arrs["feet"]
    floor = feet[~arrs["swing"]].reshape(-1, 3)[:, 2].min()
    q = arrs["q"].copy()
    for k in np.flatnonzero(arrs["swing"].any(axis=1)):
        M.forward(q[k])
        targets = {}
        for j, s in enumerate(statics.SIDES):
            pos, R = M.foot_pose(s)
            pos = pos.copy()
            if arrs["swing"][k, j]:
                pos[2] = floor + scale * (pos[2] - floor)
            targets[s] = (pos, R.copy())
        q[k], ok = statics.leg_ik(M, q[k].copy(), targets, iters=200)
        assert ok
    M.forward(src["q_home"])
    arrs["q"] = q


