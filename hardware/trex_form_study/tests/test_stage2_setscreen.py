def twist_to(src, use: float):
    """An edit that scales the two thigh-twist angles so that the worse leg uses ``use`` of its +-0.30 rad."""
    m = src["M"].m
    cols = [int(m.jnt_qposadr[statics.jid(m, f"{s}_hip_yaw")]) for s in statics.SIDES]

    def edit(arrs):
        arrs["q"] = arrs["q"].copy()
        arrs["q"][:, cols] *= use * 0.30 / np.max(np.abs(arrs["q"][:, cols]))

    return edit


