def flags(**ratios) -> dict:
    """``drive_flags``' shape from {"<group> <kind>": ratio}."""
    over = [dict(limit=k, value=v) for k, v in ratios.items() if v > 1.0]
    near = [dict(limit=k, value=v) for k, v in ratios.items() if 1.0 - setscreen.NEAR_BAND < v <= 1.0]
    a1 = any(k.split()[0] in setscreen.A1_GROUPS for k in (o["limit"] for o in over))
    leg = any(k.split()[0] not in setscreen.A1_GROUPS for k in (o["limit"] for o in over))
    return dict(over=over, near=near, a1_over=a1, over_leg_drive=leg)


def parts(kind="change", causal=False, cop=45.0, swing=0.05, twist=0.0, tightest=0.2, other=0.2, lp=0.4, differs=(),
          split_failed=0, **gates) -> dict:
    """The measured parts ``judge_move`` reads, all inside their gates unless said otherwise; None for a reading
    that is missing (``cop``, ``twist``, ``tightest``, ``other``)."""
    g = dict.fromkeys(setscreen.CLEARANCE_GATES, True) | gates
    g["swing_clearance"] = swing >= setscreen.SWING_MIN_FRAC
    rng = dict(tightest=None if tightest is None else ["left_hip_yaw", "max", tightest], hip_yaw_range_use=twist,
               usable_differs_from_plant=None if differs is None else list(differs))
    if kind == "turn":
        twist_ok = twist is not None and twist <= setscreen.TWIST_USE_MAX
        rng.update(twist_ok=twist_ok, tightest_other=None if other is None else ["left_hip_roll", "max", other],
                   ok=twist_ok and other is not None and other >= setscreen.RANGE_RULE_MOVE_RAD)
    else:
        rng.update(ok=tightest is not None and tightest >= setscreen.RANGE_RULE_MOVE_RAD)
    return dict(contact=dict(single_support_cop_margin_min_mm=cop, split_failed_frames=split_failed,
                             cop_rule_mm=1e3 * (setscreen.COP_RULE_CAUSAL_M if causal else setscreen.COP_RULE_M)),
                clear=dict(gates=g, mid_swing_min_frac_H=swing), rng=rng, accel=dict(com_forward_lp1hz_peak=lp))


def judge(kind="change", causal=False, fl=None, ik_ok=True, **kw) -> dict:
    p = parts(kind, causal, **kw)
    return setscreen.judge_move(kind, causal, fl or flags(), ik_ok, 3, p["contact"], p["clear"], p["rng"], p["accel"])


def limits_of(v: dict) -> list:
    return [o["limit"] for o in v["blocks_freeze"]]


def test_the_table_of_what_blocks_a_freeze():
    """The plan's A12, row by row, for a start, a change, a stop and a turn (``judge_move``)."""
    kinds = ("start", "change", "stop", "turn")
    for kind in kinds:
        v = judge(kind)
        assert v == dict(text="within the Stage 0 limits", within_limits=True, over=[], near=[], a1_over=False,
                         blocks_freeze=[])
        # a leg drive over a limit blocks every kind
        for limit in ("knee speed", "hip_pitch peak", "hip_yaw cont", "ankle_a speed"):
            v = judge(kind, fl=flags(**{limit: 1.03}))
            assert limits_of(v) == [limit] and not v["a1_over"] and not v["within_limits"], (kind, limit)
        # a neck or tail drive over a limit: a1_over; it blocks a straight move and not a turn
        for limit in ("tail peak", "tail cont", "neck speed", "neck cont"):
            v = judge(kind, fl=flags(**{limit: 1.2}))
            assert v["a1_over"] is True and not v["within_limits"] and [o["limit"] for o in v["over"]] == [limit]
            assert limits_of(v) == ([] if kind == "turn" else [limit]), (kind, limit)
        v = judge(kind, fl=flags(**{"tail peak": 1.2, "knee speed": 1.01}))  # both: the leg drive still blocks a turn
        assert v["a1_over"] and limits_of(v) == (["knee speed"] if kind == "turn" else ["tail peak", "knee speed"])
        # the expressive head's two drives are no appendage group: gated like the legs', on a turn too
        for limit in ("neck_yaw speed", "jaw peak"):
            v = judge(kind, fl=flags(**{limit: 1.2}))
            assert limits_of(v) == [limit] and v["a1_over"] is False, (kind, limit)
        # a gate whose reading is missing blocks every kind, and the item names the reading
        v = judge(kind, cop=None)
        assert v["blocks_freeze"] == [dict(limit="not read: single-support CoP margin", value=None)] and not v["within_limits"]
        assert v["text"] == ("not read: single-support CoP margin: blocks the freeze (not read: single-support CoP "
                             "margin)")
        v = judge(kind, split_failed=3)
        assert v["blocks_freeze"] == [dict(limit="not read: the contact split did not solve in double-support frames",
                                           value=3)]
        v = judge(kind, differs=("left_hip_yaw", "right_knee"))
        assert limits_of(v) == ["not read: the usable ranges are not plant.usable_ranges' (left_hip_yaw, right_knee)"]
        assert limits_of(judge(kind, differs=None)) == ["not read: the usable ranges were not compared with plant.usable_ranges"]
        v = judge(kind, fl=flags(**{"knee speed": 1.03}), cop=None)  # over a limit and a reading missing: both said
        assert limits_of(v) == ["knee speed", "not read: single-support CoP margin"]
        assert v["text"].startswith("over knee speed 1.0300; not read: single-support CoP margin: blocks the freeze (")
        # IK, the swing gate, interference, component overlap and the tail block every kind
        assert limits_of(judge(kind, ik_ok=False)) == ["IK"]
        assert limits_of(judge(kind, swing=0.03)) == ["clearance swing_clearance"]
        assert judge(kind, swing=0.03)["blocks_freeze"][0]["value"] == 0.03
        for gate in ("interference_free_home", "interference_free_nominal_gait", "component_overlap_free",
                     "tail_clearance"):
            assert limits_of(judge(kind, **{gate: False})) == [f"clearance {gate}"]
            assert limits_of(judge(kind, **{gate: None})) == [f"clearance {gate}"]  # not read is not passed
        # the single-support CoP rule: Stage 0's -10 mm, +10 mm for a causal move
        assert limits_of(judge(kind, cop=5.0)) == [] and limits_of(judge(kind, cop=-9.0)) == []
        assert limits_of(judge(kind, cop=-11.0)) == ["single-support CoP margin under -10 mm"]
        assert limits_of(judge(kind, causal=True, cop=5.0)) == ["single-support CoP margin under 10 mm"]
        assert limits_of(judge(kind, causal=True, cop=10.5)) == []
        # decision 10's 1 Hz forward acceleration blocks a start, a change and a stop; a turn's is reported
        v = judge(kind, lp=1.6)
        assert limits_of(v) == ([] if kind == "turn" else ["1 Hz forward acceleration above 1.5 m/s^2"])
        assert v["within_limits"] is (kind == "turn")
        assert limits_of(judge(kind, lp=1.5)) == []
    # joint range: a move's 0.05 rad on every gated joint of a straight move (the owner's decision P34; a walk's 0.10
    # rad is not a move's gate: Stage 1's own transitions come within 0.057 rad)
    assert setscreen.RANGE_RULE_MOVE_RAD == 0.05 and setscreen.RANGE_RULE_RAD == 0.10
    for kind in ("start", "change", "stop"):
        v = judge(kind, tightest=0.0499, twist=0.83)
        assert limits_of(v) == ["joint range margin under 0.05 rad (left_hip_yaw max)"]
        assert v["blocks_freeze"][0]["value"] == 0.0499
        assert limits_of(judge(kind, tightest=0.05)) == []
        assert limits_of(judge(kind, tightest=0.057)) == [] and limits_of(judge(kind, tightest=0.095)) == []
    # a turn: the thigh twist by the stride rule's 0.87; the 0.05 rad is not applied to it
    v = judge("turn", twist=0.83, tightest=0.051)
    assert v["within_limits"] and limits_of(v) == [] and v["over"] == []
    assert limits_of(judge("turn", twist=0.87, tightest=0.039)) == []
    v = judge("turn", twist=0.88, tightest=0.036)
    assert limits_of(v) == ["thigh twist use above 0.87"] and v["blocks_freeze"][0]["value"] == 0.88
    v = judge("turn", twist=0.83, tightest=0.051, other=0.049)  # another joint keeps the move's 0.05 rad
    assert limits_of(v) == ["joint range margin under 0.05 rad (left_hip_roll max)"]
    assert limits_of(judge("turn", twist=0.9, other=0.049)) == ["thigh twist use above 0.87",
                                                               "joint range margin under 0.05 rad (left_hip_roll max)"]
    # the margin of the prototype quick turn (0.0856 rad of hip roll at a twist use of 0.817) blocked under 0.10 rad;
    # under a move's 0.05 rad it does not, and 0.0499 rad does
    v = judge("turn", twist=0.817, tightest=0.0549, other=0.0856)
    assert limits_of(v) == [] and v["within_limits"] and v["blocks_freeze"] == []
    v = judge("turn", twist=0.817, tightest=0.0549, other=0.0499)
    assert limits_of(v) == ["joint range margin under 0.05 rad (left_hip_roll max)"] and v["blocks_freeze"][0]["value"] == 0.0499
    assert "joint range margin under 0.05 rad (left_hip_roll max) 0.0499: blocks the freeze" in v["text"]
    assert limits_of(judge("turn", twist=0.70, other=0.05)) == []
    # joint-range margins that were not read are not a pass: a straight move's, a turn's other joints, its twist use
    for kind in ("start", "change", "stop"):
        assert limits_of(judge(kind, tightest=None)) == ["not read: joint range margins"]
    assert limits_of(judge("turn", twist=0.5, tightest=None)) == []  # a turn reads the other joints, which are there
    assert limits_of(judge("turn", twist=0.5, other=None)) == ["not read: joint range margins of a joint other than "
                                                              "the thigh twist"]
    assert limits_of(judge("turn", twist=None)) == ["not read: thigh twist use"]
    assert limits_of(judge("turn", twist=None, other=None)) == [
        "not read: thigh twist use", "not read: joint range margins of a joint other than the thigh twist"]
    # near a limit is listed and blocks nothing
    v = judge("change", fl=flags(**{"knee speed": 0.99, "tail peak": 0.985}))
    assert v["within_limits"] and [o["limit"] for o in v["near"]] == ["knee speed", "tail peak"]
    # the sentence names what blocks, or that nothing does, with four decimals (0.0497 rad is not its 0.05 rad gate)
    assert judge("change", fl=flags(**{"knee speed": 1.03}))["text"] == "over knee speed 1.0300: blocks the freeze (knee speed)"
    assert judge("turn", fl=flags(**{"tail peak": 1.2}))["text"] == (
        "over tail peak 1.2000: does not block the freeze; a1_over, read under the plan's third reading only")
    v = judge("change", tightest=0.0497)
    assert v["text"] == ("over joint range margin under 0.05 rad (left_hip_yaw max) 0.0497: blocks the freeze (joint range "
                         "margin under 0.05 rad (left_hip_yaw max))")
    assert setscreen._item(dict(limit="joint range margin under 0.1 rad (left_hip_roll max)", value=0.0997)).endswith(" 0.0997")
    assert setscreen._item(dict(limit="IK", value=3)) == "IK 3" and setscreen._item(dict(limit="x", value=None)) == "x"
    assert judge("turn", lp=1.6)["text"] == "within the Stage 0 limits"  # a turn's acceleration is no item at all


def test_move_range_fails_a_rule_whose_reading_is_missing(monkeypatch):
    """``move_range`` with no margins: the joint-range rule and a turn's rule read false, not unread-and-passed; usable
    ranges that are not the plant's are listed."""
    usable = {"left_hip_yaw": (-0.3, 0.3), "right_hip_yaw": (-0.3, 0.3), "left_hip_roll": (-0.45, 0.2618)}
    monkeypatch.setattr(setscreen.plant, "usable_ranges", lambda body: usable)
    monkeypatch.setattr(setscreen.statics, "jid", lambda m, jn: list(usable).index(jn))
    src = dict(M=SimpleNamespace(m=SimpleNamespace(jnt_qposadr=np.arange(3))), body=BODY)
    q = np.array([[0.1, -0.2, 0.05], [0.24, 0.0, 0.1]])
    r = setscreen.move_range(src, q, "start", {}, None)
    assert (r["ok"], r["stage0_rule_ok"], r["tightest"]) == (False, False, None)
    assert r["hip_yaw_range_use"] == pytest.approx(0.8) and r["usable_differs_from_plant"] == sorted(usable)
    assert r["tightest_unrounded"] == ["left_hip_yaw", "max", pytest.approx(0.06)]
    r = setscreen.move_range(src, q, "turn", {}, None)
    assert (r["ok"], r["twist_ok"], r["tightest_other"], r["tightest_twist"]) == (False, True, None, None)
    margins = {jn: dict(walk_min=-0.2, walk_max=0.24, usable=list(v), margin_min=0.1, margin_max=0.06) for jn, v in usable.items()}
    margins["left_hip_roll"].update(walk_max=0.1, margin_min=0.25, margin_max=0.1618)
    r = setscreen.move_range(src, q, "turn", {}, margins)
    assert (r["ok"], r["twist_ok"], r["stage0_rule_ok"], r["usable_differs_from_plant"]) == (True, True, False, [])
    assert r["tightest_other"] == ["left_hip_roll", "max", 0.1618] and r["tightest_twist"] == ["left_hip_yaw", "max", 0.06]
    assert (r["rule_rad"], r["walk_rule_rad"]) == (0.05, 0.10)
    # a straight move: a move's 0.05 rad on every gated joint (0.06 rad passes it and is under a walk's 0.10 rad)
    r = setscreen.move_range(src, q, "change", {}, margins)
    assert (r["ok"], r["stage0_rule_ok"], r["rule_rad"], r["rule"]) == (True, False, 0.05, "a move: 0.05 rad on every gated joint")
    margins["left_hip_yaw"]["margin_max"] = 0.0499
    assert setscreen.move_range(src, q, "change", {}, margins)["ok"] is False
    assert setscreen.move_range(src, q, "turn", {}, margins)["ok"] is True  # a turn's twist has its own rule
    margins["left_hip_yaw"]["margin_max"] = 0.06
    margins["right_hip_yaw"]["usable"] = [-0.3, 0.31]
    del margins["left_hip_roll"]
    r = setscreen.move_range(src, q, "turn", {}, margins)
    assert r["usable_differs_from_plant"] == ["left_hip_roll", "right_hip_yaw"] and r["ok"] is False
    v = setscreen.judge_move("turn", False, flags(), True, 0, parts("turn")["contact"], parts("turn")["clear"], r,
                             parts("turn")["accel"])
    assert limits_of(v) == ["not read: joint range margins of a joint other than the thigh twist",
                            "not read: the usable ranges are not plant.usable_ranges' (left_hip_roll, right_hip_yaw)"]


