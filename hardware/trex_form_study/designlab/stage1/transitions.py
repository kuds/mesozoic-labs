def _align(pl: Plan, stride_phase: float, ref: refs.Reference):
    """The rigid motion that carries ``ref``'s stride 0 (its path frame at time 0: origin, heading 0) onto the
    plan's stride that starts at ``stride_phase``."""
    P, th = pl.pose_fn(stride_phase)
    origin = ref.path[0] if "path" in ref.arrays else None
    if origin is None:  # straight walks: gait.generate's frame, the plan's origin at time 0
        origin = pl.pose_fn(pl.first)[0]
    return (th, np.asarray(origin, float), P)


def compare(g: dict, ref: refs.Reference | None, side: str, q_home=None) -> dict:
    """The first ("a") or last ("b") output stride of a generated transition against its periodic reference (or the
    stand): CoM (model CoM, 3D, mm), multibody ZMP (mm), joint angles (rad), rates (rad/s) and feedforward torques
    (N m), the largest difference over the stride and at the join frame (the first output frame, which follows the
    first gait's last frame; the last output frame, which the second gait's first frame follows)."""
    pl, n = g["plan"], N_FRAMES
    k_out = np.arange(pl.n_out)
    if side == "a":
        sel, stride_phase, join = k_out[:n], float(pl.first), 0
    else:
        sel, stride_phase, join = k_out[-n:], float(pl.last - 1), n - 1
    com, zmb = g["com"][sel], g["zmp_mb"][sel]
    qj, qdj, tau = g["q"][sel][:, 7:], g["qd"][sel][:, 6:], g["tau"][sel]
    if ref is None:  # the stand: the home pose at the plan's stand point, at rest
        stand = pl.stand_point["initial" if side == "a" else "final"]
        com_ref = np.column_stack([np.tile(stand, (n, 1)), np.full(n, g["geo"].com0[2])])
        zmp_ref = np.tile(stand, (n, 1))
        q_ref = np.tile(np.asarray(q_home)[7:], (n, 1))
        qd_ref = np.zeros_like(qdj)
        tau_ref = None
    else:
        mot = _align(pl, stride_phase, ref)
        com_ref = np.column_stack([_move(ref.com[:, :2], mot), ref.com[:, 2]])
        zmp_ref = _move(ref.zmp_mb, mot)
        q_ref, qd_ref, tau_ref = ref.q[:, 7:], ref.qd[:, 6:], ref.tau
    dc = 1e3 * np.linalg.norm(com - com_ref, axis=1)
    dz = 1e3 * np.linalg.norm(zmb - zmp_ref, axis=1)
    dq, dqd = np.abs(qj - q_ref).max(1), np.abs(qdj - qd_ref).max(1)
    out = dict(stride_phase=stride_phase, reference="stand" if ref is None else ref.name,
               com_max_mm=float(np.max(dc)), com_mean_mm=float(np.mean(dc)), zmp_max_mm=float(np.nanmax(dz)),
               zmp_mean_mm=float(np.nanmean(dz)), joint_max_rad=float(np.max(dq)), joint_rate_max_rad_s=float(np.max(dqd)),
               at_join=dict(frame="first output frame" if side == "a" else "last output frame", com_mm=float(dc[join]),
                            zmp_mm=float(dz[join]), joint_rad=float(dq[join]), joint_rate_rad_s=float(dqd[join])))
    if tau_ref is not None:
        dt_ = np.abs(tau - tau_ref).max(1)
        out["tau_max_Nm"] = float(np.max(dt_))
        out["at_join"]["tau_Nm"] = float(dt_[join])
    out["com_ok"], out["zmp_ok"] = out["com_max_mm"] <= G3_COM_MM, out["zmp_max_mm"] <= G3_ZMP_MM
    return out


def stop_time(g: dict) -> dict | None:
    """A stop's reference, in strides from the last lift-off (phase 0): when the forward CoM speed stays below 1 % of
    the walk's speed, and when the CoM comes to rest at the final stand (within 1 mm, under 1 mm/s, from then on)."""
    pl = g["plan"]
    if pl.kind != "stop":
        return None
    ph, t = pl.phase[pl.out], pl.t[pl.out]
    c = g["com_ref"]
    v = np.gradient(c, t, axis=0)
    th_f = pl.pose_fn(float(pl.last))[1]
    fwd = np.array([math.cos(th_f), math.sin(th_f)])
    walk_speed = max(pl.a.speed, 1e-9)
    slow = np.abs(v @ fwd) < 0.01 * walk_speed if pl.a.speed > 0 else np.zeros(len(ph), bool)
    d = np.linalg.norm(c - pl.stand_point["final"], axis=1)
    rest = (d < 1e-3) & (np.linalg.norm(v, axis=1) < 1e-3)

    def settled(flags):
        k = next((i for i in range(len(flags)) if ph[i] >= 0.0 and flags[i:].all()), None)
        return None if k is None else float(ph[k])

    return dict(rule="forward: reference CoM speed along the walk below 1 % of the walk's speed from then on; rest: "
                     "within 1 mm of the final stand and slower than 1 mm/s from then on",
                forward_stopped_strides=settled(slow) if pl.a.speed > 0 else None, at_rest_strides=settled(rest),
                last_touchdown_phase=float(1.0 - pl.a.duty), single_step=True)


