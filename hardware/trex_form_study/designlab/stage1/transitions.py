def derivatives(m, qs: np.ndarray, t: np.ndarray):
    """Central-difference qvel and qacc at the interior frames (second order on a non-uniform grid; the references'
    formula where the two intervals are equal).  The first and last frame get NaN."""
    K = len(qs)
    qd = np.full((K, m.nv), np.nan)
    v, v1, v2 = np.zeros(m.nv), np.zeros(m.nv), np.zeros(m.nv)
    for k in range(1, K - 1):
        h1, h2 = t[k] - t[k - 1], t[k + 1] - t[k]
        if abs(h1 - h2) <= 1e-12 * max(h1, h2):
            mujoco.mj_differentiatePos(m, v, h1 + h2, qs[k - 1], qs[k + 1])
            qd[k] = v
        else:
            mujoco.mj_differentiatePos(m, v1, h1, qs[k - 1], qs[k])
            mujoco.mj_differentiatePos(m, v2, h2, qs[k], qs[k + 1])
            qd[k] = (h2 * v1 + h1 * v2) / (h1 + h2)
    qdd = np.full_like(qd, np.nan)
    for k in range(2, K - 2):
        h1, h2 = t[k] - t[k - 1], t[k + 1] - t[k]
        if abs(h1 - h2) <= 1e-12 * max(h1, h2):
            qdd[k] = (qd[k + 1] - qd[k - 1]) / (h1 + h2)
        else:
            qdd[k] = (h2 * (qd[k] - qd[k - 1]) / h1 + h1 * (qd[k + 1] - qd[k]) / h2) / (h1 + h2)
    return qd, qdd


def solve_frames(M: statics.Model, q_home, pl: Plan, com_t: np.ndarray, geo: Geometry):
    """Poses for the plan's frames: trunk yaw, height, neck and tail from the plan, the pelvis shifted until the
    model CoM is on ``com_t`` (``gait.generate``'s loop), the legs by ``statics.leg_ik``."""
    m = M.m
    K = len(pl.phase)
    neck = m.jnt_qposadr[statics.jid(m, "neck_pitch")]
    tail = m.jnt_qposadr[statics.jid(m, "tail_yaw")]
    off = geo.com0[:2] - geo.root0[:2]
    qs = np.zeros((K, m.nq))
    q = np.asarray(q_home, float).copy()
    foot_err = np.zeros((K, 2))
    com_err = np.zeros(K)
    for k in range(K):
        targets = {s: (pl.foot_pos[k, j], turning._rotz(pl.foot_yaw[k, j])) for j, s in enumerate(SIDES)}
        q[2] = pl.root_z[k]
        q[3:7] = turning._quat_yaw(pl.heading[k], geo.quat0)
        q[neck], q[tail] = pl.neck[k], pl.tail[k]
        q[:2] = com_t[k] - _rot2(pl.heading[k]) @ off
        for _ in range(COM_ITERS):
            q, _ok = statics.leg_ik(M, q, targets, iters=IK_ITERS)
            err = com_t[k] - M.com()[:2]
            if np.linalg.norm(err) < COM_TOL:
                break
            q[0] += err[0]
            q[1] += err[1]
        M.forward(q)
        foot_err[k] = turning._foot_errors(M, targets)
        com_err[k] = np.linalg.norm(com_t[k] - M.com()[:2])
        qs[k] = q
    return qs, foot_err, com_err


def multibody_zmp(M: statics.Model, qs, qd, qdd) -> np.ndarray:
    out = np.full((len(qs), 2), np.nan)
    for k in range(len(qs)):
        if np.all(np.isfinite(qdd[k])):
            out[k] = statics.total_zmp(M, qs[k], qd[k], qdd[k])
    return out


