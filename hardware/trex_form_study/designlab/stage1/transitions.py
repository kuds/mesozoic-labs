def preview_gains(dt: float, omega: float, qe: float = PREVIEW_QE, r: float = PREVIEW_R, preview_s: float = PREVIEW_S):
    """Cart-table matrices and the integral preview controller's gains (Katayama et al. 1985; Kajita et al. 2003):
    u_k = -Gi sum_i e_i - Gx x_k - sum_{j=1..N} Gp_j p_ref,k+j, x = (c, c', c''), p = c - c'' / omega^2."""
    A = np.array([[1.0, dt, dt * dt / 2], [0.0, 1.0, dt], [0.0, 0.0, 1.0]])
    B = np.array([dt**3 / 6, dt * dt / 2, dt])
    C = np.array([1.0, 0.0, -1.0 / omega**2])
    At = np.block([[np.ones((1, 1)), (C @ A)[None, :]], [np.zeros((3, 1)), A]])
    Bt = np.concatenate([[C @ B], B])[:, None]
    Q = np.zeros((4, 4))
    Q[0, 0] = qe
    P = scipy.linalg.solve_discrete_are(At, Bt, Q, np.array([[r]]))
    S = float((r + Bt.T @ P @ Bt)[0, 0])
    K = (Bt.T @ P @ At)[0] / S
    Gi, Gx = float(K[0]), K[1:].copy()
    Ac = At - Bt @ K[None, :]
    N = int(round(preview_s / dt))
    X = -Ac.T @ P @ np.array([1.0, 0.0, 0.0, 0.0])
    Gp = np.zeros(N)
    Gp[0] = -Gi
    for j in range(1, N):
        Gp[j] = float(Bt[:, 0] @ X) / S
        X = Ac.T @ X
    return dict(A=A, B=B, C=C, Gi=Gi, Gx=Gx, Gp=Gp, N=N, dt=dt)


def preview_run(gains: dict, zref: np.ndarray, x0: np.ndarray):
    """Run the preview controller over ``zref`` (grid samples, 1-D; at least N samples past the last output) from
    the state ``x0``; returns the states (M, 3) and jerks (M,) for the first M = len(zref) - N samples."""
    A, B, C, Gi, Gx, Gp, N = (gains[k] for k in ("A", "B", "C", "Gi", "Gx", "Gp", "N"))
    Mn = len(zref) - N
    xs, us = np.zeros((Mn, 3)), np.zeros(Mn)
    x = np.asarray(x0, float).copy()
    esum = 0.0
    for k in range(Mn):
        xs[k] = x
        esum += C @ x - zref[k]
        u = -Gi * esum - Gx @ x - Gp @ zref[k + 1 : k + 1 + N]
        us[k] = u
        x = A @ x + B * u
    return xs, us


def _move(x, motion):
    """Rigid planar motion (phi, a, b): x -> b + R(phi) (x - a), on points (..., 2)."""
    phi, a, b = motion
    return np.asarray(b) + (np.asarray(x, float) - np.asarray(a)) @ _rot2(phi).T


def _inverse(motion):
    phi, a, b = motion
    return (-phi, np.asarray(b), np.asarray(a))


def _stride_motion_at(pl: Plan, p: float):
    """The rigid motion that carries the path pose at phase p to the pose at p + 1."""
    P0, th0 = pl.pose_fn(p)
    P1, th1 = pl.pose_fn(p + 1.0)
    return (th1 - th0, P0, P1)


def com_path(pl: Plan, zref: np.ndarray, x0: np.ndarray, omega: float) -> np.ndarray:
    """CoM xy at the plan's frames by preview control of ``zref`` (frames, (K, 2)) from the state ``x0`` (3, 2) at
    the first frame (module docstring)."""
    t, K, n = pl.t, len(pl.t), N_FRAMES
    dt_min = float(np.min(np.diff(t)))
    g = preview_gains(dt_min, omega)
    # the preview past the last frame: the last stride carried on by the second gait's stride motion
    reps = int(math.ceil(PREVIEW_S / (n * dt_min))) + 2
    ext_z, ext_t = [], []
    if pl.b.stand:
        ext_t = t[-1] + dt_min * np.arange(1, reps * n + 1)
        ext_z = np.tile(zref[-1], (len(ext_t), 1))
    else:
        mot = _stride_motion_at(pl, pl.phase[-n])
        T_b = pl.b.period
        z_last = zref[-n:]
        t_last = t[-n:]
        for r_ in range(1, reps + 1):
            z_last = _move(z_last, mot)
            ext_z.append(z_last)
            ext_t.append(t_last + r_ * T_b)
        ext_z, ext_t = np.vstack(ext_z), np.concatenate(ext_t)
    tt = np.concatenate([t, ext_t])
    zz = np.vstack([zref, ext_z])
    grid = t[0] + dt_min * np.arange(int(math.floor((t[-1] - t[0]) / dt_min)) + 2 + g["N"])
    out = np.zeros((K, 2))
    for ax in (0, 1):
        zg = np.interp(grid, tt, zz[:, ax])
        xs, us = preview_run(g, zg, x0[:, ax])
        idx = np.clip(((t - t[0]) / dt_min + 1e-9).astype(int), 0, len(xs) - 1)
        s = t - grid[idx]
        out[:, ax] = xs[idx, 0] + xs[idx, 1] * s + xs[idx, 2] * s * s / 2 + us[idx] * s**3 / 6
    return out


