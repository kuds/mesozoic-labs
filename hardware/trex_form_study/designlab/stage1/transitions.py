def arrays(g: dict) -> dict:
    pl = g["plan"]
    o = pl.out
    q = g["q"]
    return dict(t=pl.t[o] - pl.t[o][0], phase=pl.phase[o], q=q, qd=g["qd"], qdd=g["qdd"], tau=g["tau"],
                omega=g["qd"][:, 6:], support=~pl.swing[o], swing=pl.swing[o], swing_u=pl.swing_u[o],
                com_ref=g["com_ref"], zmp_ref=g["zmp_ref"], zmp_mb=g["zmp_mb"], zref=g["zref"],
                cop_margin=g["cop_margin"], normal=g["normal"], friction=g["friction"], feet=g["feet"], com=g["com"],
                foot_target=pl.foot_pos[o], foot_yaw=pl.foot_yaw[o], path=pl.path[o], heading=pl.heading[o],
                stand_point=np.array([pl.stand_point["initial"], pl.stand_point["final"]]),
                q_home=np.asarray(g["q_home"]), joints=np.array(g["joints"]),
                dt=np.array(float(np.mean(np.diff(pl.t[o])))))


def _sha(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def summary(g: dict, ref_a, ref_b, q_home) -> dict:
    """``transitions.json`` entry of one generated transition, with its G3 values."""
    pl = g["plan"]
    sa = compare(g, ref_a, "a", q_home)
    sb = compare(g, ref_b, "b", q_home)
    o = pl.out
    steps = [dict(side=s, lift_off_phase=float(lo), touchdown_phase=float(td), lift_m=float(h),
                  from_xy=[float(v) for v in f0[0]], from_yaw=float(f0[1]), to_xy=[float(v) for v in f1[0]],
                  to_yaw=float(f1[1]), length_m=float(np.linalg.norm(f1[0] - f0[0])))
             for s, lo, td, h, f0, f1 in pl.swings if pl.first - 0.5 <= lo < pl.last]
    margins = g["cop_margin"]
    single = np.sum(pl.swing[o], axis=1) == 1
    return dict(name=g["name"], kind=pl.kind, from_=pl.a.name, to=pl.b.name, gaits=dict(a=asdict(pl.a), b=asdict(pl.b)),
                output_phase=[pl.first, pl.last], frames=pl.n_out, duration_s=float(pl.t[o][-1] - pl.t[o][0]),
                ramps=pl.ramps, steps=steps, zmp_iters=g["zmp_iters"], zmp_gain=g["zmp_gain"],
                zmp_error_history_m=g["zmp_error_history_m"], split=g["split"], ik_ok=g["ik_ok"],
                com_tracking_max_m=float(np.max(g["com_error"])),
                min_cop_margin_single_m=float(np.nanmin(margins[single])) if single.any() else None,
                min_cop_margin_m=float(np.nanmin(margins)), max_friction_ratio=float(np.max(g["friction"])),
                stop=stop_time(g), join_a=sa, join_b=sb,
                g3=dict(rule=f"last output stride within {G3_COM_MM:g} mm of the periodic walk's CoM and {G3_ZMP_MM:g} "
                             f"mm of its multibody ZMP ({'the home stance' if pl.b.stand else pl.b.name})",
                        com_max_mm=sb["com_max_mm"], zmp_max_mm=sb["zmp_max_mm"],
                        pass_=bool(sb["com_ok"] and sb["zmp_ok"] and g["ik_ok"])),
                seconds=g["seconds"])


def write(g: dict, ref_a, ref_b, q_home, out_dir: Path) -> dict:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{g['name']}.npz"
    np.savez(path, **arrays(g))
    entry = summary(g, ref_a, ref_b, q_home)
    entry.update(file=f"transitions/{path.name}", sha256=_sha(path))
    return entry


def _load_ref(out_dir: Path, name: str) -> refs.Reference | None:
    return None if name == "stand" else refs.Reference.load(Path(out_dir) / "refs" / f"{name}.npz")


def _job(job: dict) -> dict:
    src = refs.source(job["body"])
    g = generate(src, job["name"], _load_ref(job["out"], TRANSITIONS[job["name"]][0]), verbose=job.get("verbose"))
    a_name, b_name = TRANSITIONS[job["name"]]
    return write(g, _load_ref(job["out"], a_name), _load_ref(job["out"], b_name), src["q_home"],
                 Path(job["out"]) / "transitions")


def prepare(body: str, out_dir: Path, names: list[str] | None = None, procs: int | None = None,
            verbose: bool = False) -> dict:
    """Generate, check (G3) and save a body's transitions from its saved references (``refs.prepare``); writes
    ``<out_dir>/transitions.json`` and ``<out_dir>/transitions/``."""
    import multiprocessing as mp
    import os

    t0 = time.perf_counter()
    out_dir = Path(out_dir)
    names = names or list(TRANSITIONS)
    jobs = [dict(body=body, name=nm, out=str(out_dir), verbose=verbose) for nm in names]
    procs = min(procs or os.cpu_count() or 1, len(jobs))
    if procs <= 1:
        entries = [_job(j) for j in jobs]
    else:
        with mp.get_context("spawn").Pool(procs) as pool:
            entries = pool.map(_job, jobs, chunksize=1)
    path = out_dir / "transitions.json"
    doc = json.loads(path.read_text()) if path.exists() else dict(body=body, transitions={})
    for e in entries:
        doc["transitions"][e["name"]] = e
        print(f"  {body} {e['name']}: {e['seconds']:.0f} s, G3 CoM {e['g3']['com_max_mm']:.4f} mm, ZMP "
              f"{e['g3']['zmp_max_mm']:.4f} mm, pass {e['g3']['pass_']}", flush=True)
    doc.update(body=body, method=__doc__.split("\n\n")[0], preview=dict(qe=PREVIEW_QE, r=PREVIEW_R, preview_s=PREVIEW_S),
               shift_strides=SHIFT_STRIDES, settle_strides=SETTLE_STRIDES, path_half_width=PATH_HALF_WIDTH,
               walk_ramp_strides=WALK_RAMP_STRIDES, windows=WINDOWS, g3_com_mm=G3_COM_MM, g3_zmp_mm=G3_ZMP_MM,
               seconds=time.perf_counter() - t0, provenance=plant.provenance())
    out_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(refs._plain(doc), indent=1))
    return doc


@dataclass
class Transition:
    """One saved transition (``arrays``), like ``refs.Reference`` but finite and on its own frame times."""

    name: str
    arrays: dict

    @classmethod
    def load(cls, path) -> "Transition":
        with np.load(path, allow_pickle=False) as z:
            return cls(Path(path).stem, {k: z[k] for k in z.files})

    def __getattr__(self, key):
        try:
            return self.__dict__["arrays"][key]
        except KeyError:
            raise AttributeError(key) from None

    @property
    def n(self) -> int:
        return len(self.arrays["t"])
