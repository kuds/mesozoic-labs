@dataclass
class Geometry:
    """Home-pose quantities of the reference model the plans use."""

    feet0: dict  # side -> foot body position (3)
    pad_c: dict  # side -> pad-polygon centroid relative to the foot origin (2), foot frame = world at home
    origin: np.ndarray  # hip-pitch midpoint (2), the path frame's origin
    com0: np.ndarray  # home CoM (3)
    root0: np.ndarray  # home root position (3)
    quat0: np.ndarray  # home root quaternion
    omega: float  # LIPM frequency of the walks, sqrt(g / (com0_z - crouch))

    @classmethod
    def of(cls, M: statics.Model, q_home, crouch: float) -> "Geometry":
        M.forward(q_home)
        feet0 = {s: M.foot_pose(s)[0].copy() for s in SIDES}
        pad_c = {s: statics._polygon_centroid(M.pad_polygon(s)) - feet0[s][:2] for s in SIDES}
        origin = 0.5 * sum(M.d.xanchor[statics.jid(M.m, f"{s}_hip_pitch")][:2] for s in SIDES)
        com0 = M.com()
        return cls(feet0, pad_c, origin.copy(), com0, np.asarray(q_home[:3], float).copy(),
                   np.asarray(q_home[3:7], float).copy(), math.sqrt(G / (com0[2] - crouch)))


