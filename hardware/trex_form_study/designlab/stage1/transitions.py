# Plan
# ------------------------------------------------------------------------------------------------
@dataclass
class Plan:
    """A transition's gait plan over its computed window (module docstring); arrays are per frame."""

    name: str
    kind: str
    a: Gait
    b: Gait
    first: int  # output window [first, last) in phase
    last: int
    phase: np.ndarray
    t: np.ndarray  # s, 0 at phase ``first``
    out: slice  # the output frames within the computed ones
    foot_pos: np.ndarray  # (K, 2, 3) foot body targets
    foot_yaw: np.ndarray  # (K, 2)
    swing: np.ndarray  # (K, 2) bool
    swing_u: np.ndarray  # (K, 2) swing progress, NaN in stance
    zmp: np.ndarray  # (K, 2) ZMP target
    heading: np.ndarray  # (K,) trunk yaw
    path: np.ndarray  # (K, 2) path-frame origin
    root_z: np.ndarray  # (K,)
    neck: np.ndarray
    tail: np.ndarray
    stand_point: dict  # "initial" / "final" (2) where the plan stands
    swings: list  # (side, phase lift-off, phase touchdown, lift m, footprint from, footprint to)
    pose_fn: object  # phase -> (path origin (2), heading)
    period_fn: object  # phase -> T
    ramps: dict

    @property
    def n_out(self) -> int:
        return self.out.stop - self.out.start


def _param_fns(kind: str, a: Gait, b: Gait):
    """Phase functions of the plan's parameters (module docstring)."""
    walk = a if not a.stand else b
    if kind == "start":
        g, h = b, PATH_HALF_WIDTH
        phi_c = 0.5 - g.duty / 2
        up = lambda p: _ramp((np.asarray(p, float) - (phi_c - h)) / (2 * h))  # noqa: E731
        amp = lambda p: _ramp((np.asarray(p, float) + SHIFT_STRIDES) / (1.0 + SHIFT_STRIDES))  # noqa: E731
        fn = dict(T=lambda p: np.full_like(np.asarray(p, float), g.period), duty=lambda p: g.duty + 0 * np.asarray(p),
                  lift=lambda p: g.lift + 0 * np.asarray(p), v=lambda p: g.speed * up(p), w=lambda p: g.yaw_rate * up(p),
                  amp=amp)
        ramps = dict(path=[phi_c - h, phi_c + h], amplitude=[-SHIFT_STRIDES, 1.0], weight_shift=[-SHIFT_STRIDES, 0.0])
    elif kind == "stop":
        g, h = a, PATH_HALF_WIDTH
        phi_c = 0.5 - g.duty / 2
        down = lambda p: 1.0 - _ramp((np.asarray(p, float) - (phi_c - h)) / (2 * h))  # noqa: E731
        end = 1.0 - g.duty + SETTLE_STRIDES
        amp = lambda p: 1.0 - _ramp(np.asarray(p, float) / end)  # noqa: E731
        fn = dict(T=lambda p: np.full_like(np.asarray(p, float), g.period), duty=lambda p: g.duty + 0 * np.asarray(p),
                  lift=lambda p: g.lift + 0 * np.asarray(p), v=lambda p: g.speed * down(p),
                  w=lambda p: g.yaw_rate * down(p), amp=amp)
        ramps = dict(path=[phi_c - h, phi_c + h], amplitude=[0.0, end], settle=[1.0 - g.duty, end])
    else:
        L = WALK_RAMP_STRIDES

        def mix(xa, xb):
            return lambda p: xa + (xb - xa) * _ramp(np.asarray(p, float) / L)

        fn = dict(T=mix(a.period, b.period), duty=mix(a.duty, b.duty), lift=mix(a.lift, b.lift), v=mix(a.speed, b.speed),
                  w=mix(a.yaw_rate, b.yaw_rate), amp=lambda p: 1.0 + 0 * np.asarray(p, float))
        ramps = dict(all=[0.0, L])
    for key in ("head_amp", "tail_amp", "crouch"):
        if kind == "walk":
            fn[key] = (lambda xa, xb: (lambda p: xa + (xb - xa) * _ramp(np.asarray(p, float) / WALK_RAMP_STRIDES)))(
                getattr(a, key), getattr(b, key))
        else:
            fn[key] = (lambda x: (lambda p: x + 0 * np.asarray(p, float)))(getattr(walk, key))
    return fn, ramps


def plan(name: str, a: Gait, b: Gait, geo: Geometry, n: int = N_FRAMES) -> Plan:
    """The gait plan of a transition from ``a`` to ``b`` (module docstring)."""
    kind = kind_of(a.name, b.name)
    fn, ramps = _param_fns(kind, a, b)
    first, last = WINDOWS[kind]
    lo, hi = first - PRE_STRIDES, last + POST_STRIDES
    # --- fine phase grid: time, heading and path origin
    pf = np.arange(int(round((lo - 3) * n * SUB)), int(round((hi + 3) * n * SUB)) + 1) / (n * SUB)
    i0 = int(np.argmin(np.abs(pf - first)))
    Tf, wf, vf = fn["T"](pf), fn["w"](pf), fn["v"](pf)
    dp = 1.0 / (n * SUB)

    def cumint(y):  # cumulative trapezoid, zero at phase ``first``
        c = np.concatenate([[0.0], np.cumsum(0.5 * (y[1:] + y[:-1]) * dp)])
        return c - c[i0]

    tf = cumint(Tf)
    thf = cumint(wf * Tf)
    Pf = np.column_stack([cumint(vf * Tf * np.cos(thf)), cumint(vf * Tf * np.sin(thf))]) + geo.origin

    def pose(p):
        p = float(np.clip(p, pf[0], pf[-1]))
        return np.array([np.interp(p, pf, Pf[:, 0]), np.interp(p, pf, Pf[:, 1])]), float(np.interp(p, pf, thf))

    def period(p):
        return float(np.interp(p, pf, Tf))

    # --- swings: left lifts at integer phases, right at half-integers
    swings = {}
    for side, off in (("left", 0.0), ("right", 0.5)):
        events = [k + off for k in range(int(math.floor(lo)) - 3, int(math.ceil(hi)) + 4)]
        if kind == "start":
            events = [e for e in events if e >= 0.0]
        elif kind == "stop":
            events = [e for e in events if e <= 0.0]
        swings[side] = [(e, e + 1.0 - float(fn["duty"](e)), float(fn["lift"](e))) for e in events]

    def footprint(side, stance_from, stance_to):
        """Footprint of a stance [stance_from, stance_to] (None: before the first / after the last swing)."""
        if stance_from is None:  # the initial stand: the path frame at rest at its start
            P, th = pose(pf[0])
        elif stance_to is None:  # the final stand: the path frame's final pose
            P, th = pose(pf[-1])
        else:
            P, th = pose(0.5 * (stance_from + stance_to))
        rel = geo.feet0[side][:2] - geo.origin
        return P + _rot2(th) @ rel, th

    sw_list = []
    stances = {}  # side -> list of (from, to, xy, yaw)
    for side in SIDES:
        ev = swings[side]
        st = []
        for i in range(len(ev) + 1):
            s_from = ev[i - 1][1] if i > 0 else (None if kind == "start" else ev[0][0] - 1.0 + (1.0 - float(fn["duty"](ev[0][0] - 1.0))))
            s_to = ev[i][0] if i < len(ev) else (None if kind == "stop" else ev[-1][0] + 1.0)
            xy, th = footprint(side, s_from, s_to)
            st.append((s_from, s_to, xy, th))
        stances[side] = st
        for i, (e_lo, e_td, lift) in enumerate(ev):
            f0, f1 = st[i], st[i + 1]
            sw_list.append((side, e_lo, e_td, lift, (f0[2], f0[3]), (f1[2], f1[3])))
    # --- frames
    phase = np.arange(int(round(lo * n)), int(round(hi * n))) / n
    K = len(phase)
    t = np.interp(phase, pf, tf)
    out = slice(int(round((first - lo) * n)), int(round((last - lo) * n)))
    foot_pos, foot_yaw = np.zeros((K, 2, 3)), np.zeros((K, 2))
    swing = np.zeros((K, 2), bool)
    swing_u = np.full((K, 2), np.nan)
    for j, side in enumerate(SIDES):
        ev, st = swings[side], stances[side]
        z0 = geo.feet0[side][2]
        for k, p in enumerate(phase):
            i = int(np.searchsorted([e[0] - PHASE_TOL for e in ev], p, side="right"))  # swings lifted by p
            # i swings have lifted off by phase p; is the latest still in the air?
            if i > 0 and p < ev[i - 1][1] - PHASE_TOL:
                e_lo, e_td, lift = ev[i - 1]
                u = (p - e_lo) / (e_td - e_lo)
                a_ = float(_ramp(u))
                (xy0, th0), (xy1, th1) = (st[i - 1][2], st[i - 1][3]), (st[i][2], st[i][3])
                foot_pos[k, j, :2] = (1 - a_) * xy0 + a_ * xy1
                foot_pos[k, j, 2] = z0 + lift * math.sin(math.pi * u) ** 2
                foot_yaw[k, j] = (1 - a_) * th0 + a_ * th1
                swing[k, j], swing_u[k, j] = True, u
            else:
                foot_pos[k, j, :2], foot_pos[k, j, 2], foot_yaw[k, j] = st[i][2], z0, st[i][3]
    # --- stand points and the ZMP target

    def centroid(j, k):
        side = SIDES[j]
        return foot_pos[k, j, :2] + _rot2(foot_yaw[k, j]) @ geo.pad_c[side]

    P_i, th_i = pose(pf[0])
    P_f, th_f = pose(pf[-1])
    stand_i = P_i + _rot2(th_i) @ (geo.com0[:2] - geo.origin)
    stand_f = P_f + _rot2(th_f) @ (geo.com0[:2] - geo.origin)
    lifts = sorted((e[0], j) for j, side in enumerate(SIDES) for e in swings[side])
    downs = sorted((e[1], j) for j, side in enumerate(SIDES) for e in swings[side])
    zmp = np.zeros((K, 2))
    for k, p in enumerate(phase):
        sup = [j for j in (0, 1) if not swing[k, j]]
        if len(sup) == 1:
            zmp[k] = centroid(sup[0], k)
            continue
        prev = [d for d in downs if d[0] <= p + PHASE_TOL]
        nxt = [u for u in lifts if u[0] > p + PHASE_TOL]
        if not prev:  # the initial stand and the weight shift (start)
            j_first = nxt[0][1]
            j_stance = 1 - j_first
            a_ = float(np.clip((p + SHIFT_STRIDES) / SHIFT_STRIDES, 0.0, 1.0))
            zmp[k] = (1 - a_) * stand_i + a_ * centroid(j_stance, k)
        elif not nxt:  # after the last touchdown (stop): to the final stand
            p_td, j_land = prev[-1]
            a_ = float(np.clip((p - p_td) / SETTLE_STRIDES, 0.0, 1.0))
            zmp[k] = (1 - a_) * centroid(1 - j_land, k) + a_ * stand_f
        else:
            p_td, j_land = prev[-1]
            p_lo, j_lift = nxt[0]
            a_ = float(np.clip((p - p_td) / (p_lo - p_td), 0.0, 1.0))
            zmp[k] = (1 - a_) * centroid(j_lift, k) + a_ * centroid(j_land, k)
    heading = np.interp(phase, pf, thf)
    path = np.column_stack([np.interp(phase, pf, Pf[:, 0]), np.interp(phase, pf, Pf[:, 1])])
    amp = fn["amp"](phase)
    root_z = geo.root0[2] - amp * fn["crouch"](phase)
    neck = amp * fn["head_amp"](phase) * np.sin(4 * np.pi * phase)
    tail = amp * fn["tail_amp"](phase) * np.sin(2 * np.pi * phase + np.pi / 2)
    return Plan(name=name, kind=kind, a=a, b=b, first=first, last=last, phase=phase, t=t, out=out, foot_pos=foot_pos,
                foot_yaw=foot_yaw, swing=swing, swing_u=swing_u, zmp=zmp, heading=heading, path=path, root_z=root_z,
                neck=neck, tail=tail, stand_point=dict(initial=stand_i, final=stand_f), swings=sorted(sw_list, key=lambda s: s[1]),
                pose_fn=pose, period_fn=period, ramps=ramps)


