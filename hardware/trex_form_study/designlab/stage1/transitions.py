"""Stage 1 transitions: starts, stops, speed changes and turn entries (``STAGE1_PLAN.md`` section 2, section 3
step 4, gate G3).

The periodic references (``refs``) are one steady stride each.  A transition joins two of them, or a reference and
the home stance ("stand"): it is generated by ZMP preview control on the designlab model, with ``statics.leg_ik``
and the same multibody-ZMP correction passes as ``gait.generate``, and it is joined to the periodic references at
stride boundaries.

Gait plan (all timing in gait phase, n = 160 frames per stride as in the references)
-------------------------------------------------------------------------------
* Phase 0 is the transition's stride boundary (a left lift-off); the left foot lifts at integer phases and the
  right at half-integers, as in ``gait.generate``.  A swing that lifts off at phase p lands at p + 1 - duty(p).
* Every timing and path parameter is a function of phase: the period T, the duty, the lift, the path speed v and
  yaw rate w, the neck and tail amplitudes and the crouch.  Real time is t = integral T dphase; the path frame
  integrates heading' = w T and position' = v T (cos heading, sin heading), starting at the reference's own origin
  (the hip-pitch midpoint of the home pose, as ``turning.generate``) at the first output frame.
* Footprints follow the references' rule: the home foot pose carried by the path frame to mid-stance.  A stance
  that began in the initial stand keeps the home pose (the path frame at rest before the transition); a stance that
  never ends (the final stand of a stop) takes the path frame's final pose.  Swing feet move between consecutive
  footprints with ``gait.generate``'s profiles (minimum-jerk position and yaw, sine-squared lift).
* The ZMP target is the references' (the stance pad centroid in single support, a linear hand-over from the foot
  about to lift to the foot that just landed in double support), plus the stand: at the home CoM before a start,
  moving to the first stance foot over ``SHIFT_STRIDES`` before the first lift-off (the weight shift), and from
  the last stance foot to the final stand's CoM over ``SETTLE_STRIDES`` after the last touchdown of a stop.
* The trunk keeps its home roll and pitch and yaws with the path frame; its height drops by the crouch and the
  neck and tail oscillate (``gait.generate``'s laws in phase) scaled by an amplitude that ramps from 0 (stand)
  to 1 (walking) over a start and back over a stop.

The transitions (``TRANSITIONS``):

* ``start`` (stand to a walk) and ``start_in_place_*`` (stand to an in-place turn): the left foot lifts first, at
  phase 0, after the weight shift.  The path speed and yaw rate ramp from 0 over [phi_c - 0.2, phi_c + 0.2]
  (min-jerk), phi_c = 0.5 - duty / 2, the mid-stance of the stance the right foot would have had in the periodic
  walk: since the ramp is antisymmetric about phi_c, every footprint from the second step on is exactly the
  periodic walk's (shifted), the left foot's first step is half a stride and the right foot's first is a full one.
* ``stop`` and ``stop_in_place_*``: the left foot's lift-off at phase 0 is the last step; it lands beside the right
  foot, in the home stance, and nothing lifts after it (one step, then double support: ``STAGE1_PLAN.md`` section
  4).  The path speed and yaw rate ramp to 0 over the same window about phi_c, so the final path pose is the
  periodic walk's at phi_c and the right foot's last footprint is the periodic one.
* Gait-to-gait (speed changes ``nominal_to_brisk`` and back, ``brisk_to_fr05`` and back; turn entries
  ``enter_*`` and exits ``exit_*``): every parameter ramps from the first gait's to the second's over phases
  [0, ``WALK_RAMP_STRIDES``] (min-jerk).

Centre of mass: ZMP preview control (Kajita et al. 2003, with the integral form of Katayama et al. 1985) on the
cart-table model x'' = w0^2 (x - p), w0^2 = g / z_c with the references' z_c (home CoM height less the crouch),
weights Qe = ``PREVIEW_QE`` on the ZMP error and R = ``PREVIEW_R`` on the jerk, ``PREVIEW_S`` of preview, on a
uniform time grid (the smallest frame interval; frames between grid points are read from the exact cubic of the
piecewise-constant jerk).  The controller starts from the first gait's CoM state one stride before the first
output frame (at rest for a stand), and its preview past the computed frames is the last computed stride carried
on by the second gait's stride motion (a constant for a stand).  On a periodic ZMP reference it reproduces the
periodic linear-inverted-pendulum solution of ``gait.generate`` to about 10 um.  The pelvis is then shifted until
the model's CoM is on that path (``gait.generate``'s loop: 1e-6 m, 12 passes at round two's accuracy), the legs
come from ``statics.leg_ik``, and the ZMP reference is corrected against the multibody ZMP (``statics.total_zmp``
with central differences over the frames, second order on the non-uniform grid of a speed change) with the
second gait's passes and gain (6 x 0.5), as ``gait.generate`` corrects the periodic walk.

Inverse dynamics: as the references, ``statics.contact_torques`` for the straight walks and
``turning.contact_torques`` (exact split) when either gait is a turn, frame by frame on the transition's support.

Gate G3 (``g3``): over the last output stride the transition must be within ``G3_COM_MM`` (1 mm) of the periodic
walk's CoM (the model CoM, 3D) and ``G3_ZMP_MM`` (2 mm) of its multibody ZMP, the walk carried to the transition's
frame by the rigid planar motion that maps its path frame onto the transition's; for a stop the "walk" is the home
stance at the final path pose (its CoM, and the ZMP at the CoM's projection).  The first output stride is compared
with the first gait in the same way (the join at the start: the transition's first frame follows the first gait's
last), and the joint angles, rates and feedforward torques at both joins are recorded.  ``STAGE1_PLAN.md`` falls
back to Design 3's amplitude ramps for a transition that fails G3; ``g3`` records which transitions would need it.

Files: ``transitions.json`` (plans, G3 values, provenance) and ``transitions/<name>.npz`` (arrays, the references'
keys plus ``phase``, ``foot_target``, ``foot_yaw``, ``swing``, ``swing_u``, ``path``, ``heading``;
``Transition.load``).
"""

