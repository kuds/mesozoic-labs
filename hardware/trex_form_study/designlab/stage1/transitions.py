def _stride_motion(ref: refs.Reference):
    sm = ref.stride_motion
    return (float(sm[0]), sm[1:3].copy(), sm[3:5].copy())


def initial_state(pl: Plan, ref_a: refs.Reference | None, geo: Geometry) -> np.ndarray:
    """(c, c', c'') per axis (3, 2) at the first computed frame: at rest for a stand, else the first gait's CoM path
    (``com_ref``) one stride before the output window (4th-order differences across the stride boundary)."""
    if pl.a.stand:
        x0 = np.zeros((3, 2))
        x0[0] = pl.stand_point["initial"]
        return x0
    mot = _stride_motion(ref_a)
    inv = _inverse(mot)
    c = ref_a.com_ref
    n, dt = ref_a.n, ref_a.step
    k0 = int(round((pl.phase[0] - pl.first) * n))  # stride offset of the first computed frame (a whole stride)
    strides = k0 // n
    if k0 % n:
        raise ValueError("the computed window must start at a stride boundary")

    def at(k):  # CoM at frame k of stride ``strides`` (k may leave [0, n))
        s, kk = divmod(k, n)
        x = c[kk]
        for _ in range(abs(strides + s)):
            x = _move(x, inv if strides + s < 0 else mot)
        return x

    p = np.array([at(k) for k in (-2, -1, 0, 1, 2)])
    x0 = np.zeros((3, 2))
    x0[0] = p[2]
    x0[1] = (-p[4] + 8 * p[3] - 8 * p[1] + p[0]) / (12 * dt)
    x0[2] = (-p[4] + 16 * p[3] - 30 * p[2] + 16 * p[1] - p[0]) / (12 * dt * dt)
    return x0


def generate(src: dict, name: str, ref_a: refs.Reference | None = None, verbose: bool = False) -> dict:
    """One transition of ``src``'s body (``refs.source``): plan, CoM, poses, derivatives, multibody-ZMP correction
    and inverse dynamics (module docstring).  ``ref_a`` is the first gait's periodic reference (required unless it
    is the stand)."""
    gait.set_accuracy(refs.ACCURACY)
    t0 = time.perf_counter()
    M, q_home, H, body = src["M"], src["q_home"], src["H"], src["body"]
    a_name, b_name = TRANSITIONS[name]
    a, b = gait_of(body, a_name, H), gait_of(body, b_name, H)
    walk = b if a.stand else a
    geo = Geometry.of(M, q_home, walk.crouch)
    pl = plan(name, a, b, geo)
    x0 = initial_state(pl, ref_a, geo)
    zref = pl.zmp.copy()
    iters = walk.zmp_iters if b.stand else b.zmp_iters
    gain = walk.zmp_gain if b.stand else b.zmp_gain
    history = []
    for it in range(iters + 1):
        com_t = com_path(pl, zref, x0, geo.omega)
        qs, foot_err, com_err = solve_frames(M, q_home, pl, com_t, geo)
        qd, qdd = derivatives(M.m, qs, pl.t)
        zmb = multibody_zmp(M, qs, qd, qdd)
        e = np.nan_to_num(zmb - pl.zmp)
        history.append(float(np.max(np.linalg.norm(e[pl.out], axis=1))))
        if verbose:
            print(f"  {name} pass {it}: ZMP error max {1e3 * history[-1]:.3f} mm ({time.perf_counter() - t0:.0f} s)",
                  flush=True)
        if it == iters:
            break
        zref = zref - gain * e
    o = pl.out
    split = "exact" if "exact" in (a.split, b.split) else "statics"
    tau, cop_margin, normal, friction = idyn(M, qs[o], qd[o], qdd[o], pl.swing[o], split)
    feet = np.zeros((pl.n_out, 2, 3))
    com = np.zeros((pl.n_out, 3))
    for i, k in enumerate(range(o.start, o.stop)):
        M.forward(qs[k])
        feet[i] = [M.foot_pose(s)[0] for s in SIDES]
        com[i] = M.com()
    return dict(name=name, plan=pl, geo=geo, a=a, b=b, q=qs[o], qd=qd[o], qdd=qdd[o], tau=tau, com_ref=com_t[o],
                zmp_ref=pl.zmp[o], zmp_mb=zmb[o], zref=zref[o], cop_margin=cop_margin, normal=normal, friction=friction,
                feet=feet, com=com, foot_error=foot_err[o], com_error=com_err[o], zmp_error_history_m=history,
                zmp_iters=iters, zmp_gain=gain, split=split, x0=x0, seconds=time.perf_counter() - t0,
                ik_ok=bool(np.all(foot_err[o] <= turning.IK_TOL)), q_home=np.asarray(q_home, float).copy(),
                joints=list(M.names))


def idyn(M: statics.Model, qs, qd, qdd, swing, split: str):
    """Feedforward joint torques and per-foot contact values on the plan's support (module docstring)."""
    K = len(qs)
    tau = np.zeros((K, len(M.act_dofs)))
    cop_margin = np.full((K, 2), np.nan)
    normal = np.zeros((K, 2))
    friction = np.zeros(K)
    for k in range(K):
        sup = tuple(s for j, s in enumerate(SIDES) if not swing[k, j]) or SIDES
        if split == "exact":
            tk, wr, _ = turning.contact_torques(M, qs[k], qd[k], qdd[k], sup, split="exact")
        else:
            tk, wr = statics.contact_torques(M, qs[k], qd[k], qdd[k], support=sup)
        tau[k] = tk
        for j, side in enumerate(SIDES):
            if side in wr:
                f = wr[side][:3]
                normal[k, j] = f[2]
                friction[k] = max(friction[k], float(np.linalg.norm(f[:2]) / max(f[2], 1e-6)))
                c = statics.cop(M, side, wr[side])
                M.forward(qs[k])
                cop_margin[k, j] = statics.support_margin(c, M.pad_polygon(side))
    return tau, cop_margin, normal, friction


