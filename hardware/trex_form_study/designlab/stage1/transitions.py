PATH_HALF_WIDTH = 0.2
#: Gait-to-gait: length of every parameter ramp (strides).
WALK_RAMP_STRIDES = 1.0
#: Output windows [first, last) in phase: the computed window adds one stride before (the preview controller's
#: start, discarded) and a quarter stride after (derivatives and the preview's continuation).
WINDOWS = {"start": (-2, 3), "stop": (-2, 3), "walk": (-2, 4)}
PRE_STRIDES = 1.0
POST_STRIDES = 0.25
#: Gate G3 (plan section 3 step 4).
