def check(groups=GROUPS, quiet: bool = False, show: int = 6) -> int:
    """Per group, the listed files here with their sha256, missing or wrong, and the list against the records; exit
    status 0 only when every file matches and every list agrees."""
    status = 0
    rows = []
    for g in groups:
        files = listed(g)
        t = tally(files)
        disagree = agreement(g)
        ok = not t["missing"] and not t["wrong"] and not disagree
        status |= 0 if ok else 1
        rows.append((g, len(files), t, disagree))
    if quiet and not status:
        return 0
    print(f"{'group':<13} {'files':>5} {'matching':>8} {'missing':>7} {'wrong':>5}  records")
    for g, n, t, disagree in rows:
        print(f"{g:<13} {n:>5} {len(t['ok']):>8} {len(t['missing']):>7} {len(t['wrong']):>5}  "
              f"{'agree' if not disagree else f'{len(disagree)} disagreements'}   ({TITLES[g]})")
    for g, _, t, disagree in rows:
        for label, items in (("missing", t["missing"]), ("wrong", t["wrong"]), ("records", disagree)):
            if items:
                print(f"  {g} {label}: " + "; ".join(items[:show]) + (f"; ... {len(items) - show} more"
                                                                      if len(items) > show else ""))
    print("all here with their listed sha256" if not status else "not all here: python tools/restore_inputs.py "
          "restore (or copy-from DIR)")
    print("not restored by this tool: " + "; ".join(w for w, _, _ in NOT_RESTORED)
          + " (python tools/restore_inputs.py not-restored)")
    return status


def not_restored_here() -> list[tuple[str, int | None, str]]:
    """(what, how many of its git-ignored paths this checkout holds (None: kept outside it), why) per ``NOT_RESTORED``
    item; the inputs' own model directories (the groups) are not counted."""
    tracked = set(subprocess.run(["git", "-C", str(STUDY), "ls-files", "--", "."], capture_output=True, text=True,
                                 check=True).stdout.splitlines())
    inputs = {Path(p).parent for g in ("picks-models", "k", "x") for p in listed(g)}
    out = []
    for what, globs, why in NOT_RESTORED:
        found = {p.relative_to(STUDY) for g in globs for p in STUDY.glob(g)}
        found = [p for p in found if p.as_posix() not in tracked and p not in inputs]
        out.append((what, len(found) if globs else None, why))
    return out


def not_restored() -> int:
    """Print what this tool cannot restore, why, and what this checkout holds of it."""
    print("Not restored by this tool:")
    for what, n, why in not_restored_here():
        print(f"* {what} ({'kept outside the checkout' if n is None else f'{n} here'}): {why}")
    return 0


def manifest(src_dir: str | None = None) -> int:
    """Write ``stage1_inputs.json`` from the picks' files in ``src_dir`` (another checkout; default this one), refusing
    a file that is missing there or differs from its record, or records that disagree."""
    src = _study_of(src_dir) if src_dir else STUDY
    files, bad = {}, []
    for body in PICKS:
        rec, problems = recorded(body)  # this checkout's records
        bad += problems
        for path, want in rec.items():
            got = _sha(src / path)
            if got is None or (want is not None and got != want):
                bad.append(f"{path}: {'missing' if got is None else f'sha256 {got[:8]}, record {want[:8]}'} in {src}")
            files[path] = got
    if bad:
        print("not written:\n  " + "\n  ".join(bad))
        return 1
    MANIFEST.write_text(json.dumps(dict(rule=RULE, bodies=list(PICKS), cases={b: case_of(b) for b in PICKS},
                                        files=dict(sorted(files.items()))), indent=1) + "\n")
    print(f"{MANIFEST.relative_to(STUDY)}: {len(files)} files, from {src}")
    return 0


