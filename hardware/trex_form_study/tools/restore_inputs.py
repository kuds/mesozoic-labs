def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    internal = {"_size": _size, "_refs": _refs, "_transitions": _transitions}
    if argv and argv[0] in internal:  # a child process of restore
        return internal[argv[0]](*argv[1:])
    os.environ.setdefault("MUJOCO_GL", "disable")  # nothing here renders (tests/conftest.py)
    ap = argparse.ArgumentParser(prog="python tools/restore_inputs.py", description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog="\n\n".join(__doc__.split("\n\n")[-2:]))
    sub = ap.add_subparsers(dest="cmd", required=True)
    groups = dict(nargs="+", action="extend", choices=GROUPS, metavar="GROUP",
                  help=f"one or more of {', '.join(GROUPS)} (default: all)")
    c = sub.add_parser("check", help="each group's files here, missing or wrong, and its list against the records")
    c.add_argument("--group", **groups)
    r = sub.add_parser("restore", help="regenerate missing or wrong files from the committed records")
    r.add_argument("--group", **groups)
    r.add_argument("--procs", type=int, default=2, help="processes at a time (default 2)")
    r.add_argument("--scratch", help="where the scratch directories go (default: the system's temporary directory)")
    f = sub.add_parser("copy-from", help="checked copy from another checkout")
    f.add_argument("dir", help="the other checkout (its repository root or its hardware/trex_form_study)")
    f.add_argument("--group", **groups)
    sub.add_parser("not-restored", help="what this tool cannot restore, and why")
    m = sub.add_parser("manifest", help="rewrite stage1/runs/2026-11-08/stage1_inputs.json from a checkout's files")
    m.add_argument("--from", dest="src", help="the checkout to read (default: this one)")
    a = ap.parse_args(argv)
    sel = tuple(g for g in GROUPS if g in (getattr(a, "group", None) or GROUPS))
    if a.cmd == "check":
        return check(sel)
    if a.cmd == "restore":
        os.setpriority(os.PRIO_PROCESS, 0, max(10, os.getpriority(os.PRIO_PROCESS, 0)))
        status = restore(sel, a.procs, a.scratch)
        print()
        not_restored()
        return status
    if a.cmd == "copy-from":
        return copy_from(a.dir, sel)
    if a.cmd == "not-restored":
        return not_restored()
    return manifest(a.src)


if __name__ == "__main__":
    sys.exit(main())
