def copy_from(src_dir: str, groups=GROUPS) -> int:
    """Copy every listed file of ``groups`` that is missing or wrong here from another checkout, each checked by its
    sha256 (the helpers' own ``copy-from`` for ``k`` and ``x``)."""
    src = _study_of(src_dir)
    if src == STUDY:
        raise SystemExit(f"copy-from {src_dir}: that is this checkout")
    status = 0
    for g in GROUPS:
        if g not in groups:
            continue
        if g in HELPERS:
            print(f"== {g}: {HELPERS[g].name} copy-from {src}", flush=True)
            status |= subprocess.run([sys.executable, str(HELPERS[g]), "copy-from", str(src)], cwd=STUDY,
                                     env=_env(1, Path(tempfile.gettempdir()))).returncode != 0
            continue
        bad = _bad(listed(g))
        put, refused = put_matching(bad, src)
        print(f"== {g}: copied {len(put)}, already here {len(listed(g)) - len(bad)}" + "".join(f"\n  {p}" for p in put))
        if refused:
            print(f"not copied ({len(refused)}), in {src}:\n  " + "\n  ".join(refused))
            status = 1
    return status | check([g for g in GROUPS if g in groups])


