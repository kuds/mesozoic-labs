def _stage1():
    if str(STUDY) not in sys.path:
        sys.path.insert(0, str(STUDY))
    import designlab  # noqa: F401  (selects the GL backend before mujoco is imported)
    from designlab import stage1

    return stage1


def case_of(body: str) -> str:
    return Path(_stage1().BODIES[body]).name


def model_paths(body: str) -> tuple[str, str]:
    """A body's round-two model files (XML, ledger JSON), relative to hardware/trex_form_study."""
    s1 = _stage1()
    d, cid = Path(s1.BODIES[body]) / "models", s1.candidate_id(body)
    return (d / f"{cid}.xml").as_posix(), (d / f"{cid}.json").as_posix()


def _entries(body: str, kind: str, study: Path = STUDY) -> dict:
    doc = _json(study / RUN.relative_to(STUDY) / body / f"{kind}.json")
    return doc["references"] if kind == "refs" else doc["transitions"]


def array_paths(body: str, kind: str, study: Path = STUDY) -> dict[str, tuple[str, str]]:
    """name -> (path relative to the study, the sha256 ``refs.json`` / ``transitions.json`` records) of a pick."""
    run = RUN.relative_to(STUDY).as_posix()
    return {n: (f"{run}/{body}/{e['file']}", e["sha256"]) for n, e in _entries(body, kind, study).items()}


def keyed_inputs(body: str, study: Path = STUDY) -> dict[str, dict[str, list[str]]]:
    """field (record, mjcf, ledger, clearance) -> sha256 -> the committed eval summaries whose session keys hold it
    (``stage1/runs/*/<body>/eval/summary.json``, ``sessions[].key_context.plant_inputs``)."""
    out: dict[str, dict[str, list[str]]] = {}
    for p in sorted(study.glob(f"stage1/runs/*/{body}/eval/summary.json")):
        rel = p.relative_to(study).as_posix()
        for s in _json(p).get("sessions", []):
            for field, sha in ((s.get("key_context") or {}).get("plant_inputs") or {}).items():
                where = out.setdefault(field, {}).setdefault(sha, [])
                if rel not in where:
                    where.append(rel)
    return out


def recorded(body: str, study: Path = STUDY) -> tuple[dict[str, str | None], list[str]]:
    """A pick's files: (path -> the sha256 the committed records hold, None where none does; where those records
    disagree among themselves)."""
    s1 = _stage1()
    xml, ledger = model_paths(body)
    rec = _json(study / s1.BODIES[body] / "candidates" / f"{s1.candidate_id(body)}.json")
    keyed, problems = keyed_inputs(body, study), []
    if not rec["xml_sha256"].startswith(s1.SHA256_PREFIX[body]):
        problems.append(f"{xml}: the candidate record's xml_sha256 {rec['xml_sha256'][:8]} lacks the plan's prefix "
                        f"{s1.SHA256_PREFIX[body]} (designlab.stage1.SHA256_PREFIX)")
    for field, path in (("mjcf", xml), ("ledger", ledger)):
        shas = keyed.get(field, {})
        if len(shas) > 1:
            problems.append(f"{path}: the eval records' keys hold {len(shas)} sha256 ("
                            + ", ".join(f"{s[:8]} in {', '.join(w)}" for s, w in shas.items()) + ")")
    problems += [f"{xml}: the eval records' keys hold {s[:8]}, the candidate record {rec['xml_sha256'][:8]}"
                 for s in keyed.get("mjcf", {}) if s != rec["xml_sha256"]]
    led = keyed.get("ledger", {})
    out: dict[str, str | None] = {xml: rec["xml_sha256"], ledger: next(iter(led)) if len(led) == 1 else None}
    if not led:
        problems.append(f"{ledger}: no committed eval record's key holds its sha256")
    for kind in ("refs", "transitions"):
        out.update(dict(array_paths(body, kind, study).values()))
    # Stage 2's screen regenerated the nominal, brisk and fr05 references and recorded their sha256 (gate G2)
    screen = study / "stage2" / "look" / "screen.json"
    g2 = ((_json(screen).get("g2") or {}).get(body) or {}).get("references", {}) if screen.exists() else {}
    refs = array_paths(body, "refs", study)
    problems += [f"{refs[n][0]}: stage2/look/screen.json's G2 has {(e.get('sha256') or '-')[:8]}, refs.json "
                 f"{refs[n][1][:8]}" for n, e in sorted(g2.items()) if n in refs and e.get("sha256") != refs[n][1]]
    return out, problems


def _is_model(path: str) -> bool:
    return path.startswith("round2/")


def listed(group: str) -> dict[str, str]:
    """A group's list: path (relative to the study) -> sha256."""
    if group in ("picks-models", "picks-arrays"):
        return {p: s for p, s in _json(MANIFEST)["files"].items() if _is_model(p) == (group == "picks-models")}
    if group in HELPERS:
        return _json(HELPERS[group].with_suffix(".json"))["files"]
    if group == "look":
        doc = _json(LOOK_REFS)
        return {(LOOK / e["file"]).relative_to(STUDY).as_posix(): e["sha256"]
                for speeds in doc["bodies"].values() for entries in speeds.values() for e in entries.values()}
    raise KeyError(group)


def helper(group: str):
    """The helper module of ``k`` or ``x``, imported from its file."""
    path = HELPERS[group]
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def helper_bodies(group: str) -> tuple[str, ...]:
    return tuple(_json(HELPERS[group].with_suffix(".json"))["bodies"])


def _look_records() -> list[tuple[str, str, str]]:
    """(record, path, sha256) of every committed record beside ``look_refs.json`` that names a rung's arrays: the
    screen (``screen.json`` rungs), the metrics and the clips (``rung_sha256``)."""
    out = []
    screen = LOOK / "screen.json"
    if screen.exists():
        for speeds in _json(screen).get("rungs", {}).values():
            for rungs in speeds.values():
                for r in rungs.values():
                    a = r.get("arrays") or {}
                    if a.get("file"):
                        out.append(("stage2/look/screen.json", a["file"], a.get("sha256")))
    metrics = LOOK / "metrics.json"
    if metrics.exists():
        for body, speeds in _json(metrics).get("bodies", {}).items():
            for speed, rungs in speeds.items():
                for v, r in rungs.items():
                    if isinstance(r, dict) and "rung_sha256" in r:
                        out.append(("stage2/look/metrics.json", f"refs/{body}/{speed}/{v}.npz", r["rung_sha256"]))
    clips = LOOK / "clips.json"
    if clips.exists():
        out += [("stage2/look/clips.json", c["rung_file"], c["rung_sha256"]) for c in _json(clips).get("clips", [])]
    return [(rec, (LOOK / f).relative_to(STUDY).as_posix(), s) for rec, f, s in out]


def agreement(group: str) -> list[str]:
    """Where a group's list disagrees with the committed records, or the records among themselves (empty: they
    agree)."""
    files, out = listed(group), []
    rec: dict[str, str | None] = {}
    if group in ("picks-models", "picks-arrays"):
        for body in PICKS:
            r, problems = recorded(body)
            rec.update({p: s for p, s in r.items() if _is_model(p) == (group == "picks-models")})
            out += [x for x in problems if _is_model(x.split(":")[0]) == (group == "picks-models")]
    elif group in HELPERS:
        h = helper(group)
        for body in helper_bodies(group):
            rec.update(h.recorded(body))
            for field, path in zip(("mjcf", "ledger"), h.model_paths(body), strict=True):
                out += [f"{path}: an eval record's key holds {s[:8]}, {HELPERS[group].with_suffix('.json').name} "
                        f"{(files.get(path) or '-')[:8]}" for s in keyed_inputs(body).get(field, {})
                        if s != files.get(path)]
    elif group == "look":
        rec = dict(files)  # look_refs.json is the record; the others must name the same arrays
        out += [f"{path}: {r} has {(s or '-')[:8]}, look_refs.json {(files.get(path) or '-')[:8]}"
                for r, path, s in _look_records() if files.get(path) != s]
    out += [f"{p}: in the records, not in the list" for p in sorted(set(rec) - set(files))]
    out += [f"{p}: in the list, not in the records" for p in sorted(set(files) - set(rec))]
    out += [f"{p}: the list has {files[p][:8]}, the record {want[:8]}" for p, want in sorted(rec.items())
            if p in files and want is not None and files[p] != want]
    return sorted(set(out))


