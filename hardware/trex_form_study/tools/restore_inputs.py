def _bad(files: dict[str, str]) -> dict[str, str]:
    return {p: s for p, s in files.items() if _sha(STUDY / p) != s}


def _report(what: str, put: list[str], refused: list[str]) -> int:
    print(f"{what}: {len(put)} put in place" + "".join(f"\n  {p}" for p in put))
    if refused:
        print(f"{what}: {len(refused)} regenerated with another sha256 or not made, not put in place:\n  "
              + "\n  ".join(refused))
    return 1 if refused else 0


def restore_picks_models(procs: int, scratch: Path) -> int:
    files = listed("picks-models")
    bad = _bad(files)
    todo = [b for b in PICKS if any(p in bad for p in model_paths(b))]
    if not todo:
        print("picks-models: all here with their listed sha256")
        return 0
    with tempfile.TemporaryDirectory(prefix="restore_models_", dir=scratch) as tmp:
        jobs = []
        for b in todo:
            (Path(tmp) / b).mkdir()
            jobs.append((b, _me("_size", b, str(Path(tmp) / b)), _env(1, scratch, blas=SIZE_BLAS_THREADS)))
        print(f"picks-models: sizing {', '.join(todo)} ({min(procs, len(jobs))} at a time, {SIZE_BLAS_THREADS} BLAS "
              "threads each; about 2.5 min each)", flush=True)
        rc = run_all(jobs, procs)
        status = 0
        for b in todo:
            mine = {p: files[p] for p in model_paths(b)}
            if rc[b]:
                print(f"picks-models: {b}'s sizing failed (exit status {rc[b]})")
                status = 1
                continue
            got = {p: _sha(Path(tmp) / b / p) for p in mine}
            if any(got[p] != mine[p] for p in mine):  # a body's two files go in together or not at all
                status = 1
                print(f"picks-models: {b} regenerated with other sha256 (" + ", ".join(
                    f"{Path(p).name} {(got[p] or 'missing')[:8]} vs {mine[p][:8]}" for p in mine) + "); not put in place")
                continue
            put, _ = put_matching(_bad(mine), Path(tmp) / b)
            print(f"picks-models: {b} regenerated, matching {MANIFEST.name}: " + ", ".join(put))
    return status


def restore_picks_arrays(procs: int, scratch: Path) -> int:
    status = 0
    with tempfile.TemporaryDirectory(prefix="restore_arrays_", dir=scratch) as tmp:
        # references: one process per body, the bodies at once
        todo = {b: sorted(n for n, (p, s) in array_paths(b, "refs").items() if _sha(STUDY / p) != s) for b in PICKS}
        jobs = [(b, _me("_refs", b, str(Path(tmp) / "refs" / b), *names), _env(1, scratch))
                for b, names in todo.items() if names]
        if jobs:
            print("picks-arrays: references of " + ", ".join(f"{b} ({len(todo[b])})" for b, *_ in jobs), flush=True)
            rc = run_all(jobs, procs)
            for b, *_ in jobs:
                want = {array_paths(b, "refs")[n][0]: array_paths(b, "refs")[n][1] for n in todo[b]}
                src = Path(tmp) / "refs" / b
                put, refused = put_matching({Path(p).relative_to(RUN.relative_to(STUDY) / b).as_posix(): s
                                             for p, s in want.items()}, src, RUN / b)
                status |= _report(f"picks-arrays {b} refs", put, refused) | (rc[b] != 0)
        # transitions: one body at a time on procs processes, from the references here
        for b in PICKS:
            names = sorted(n for n, (p, s) in array_paths(b, "transitions").items() if _sha(STUDY / p) != s)
            if not names:
                continue
            if any(_sha(STUDY / p) != s for p, s in array_paths(b, "refs").values()):
                print(f"picks-arrays {b} transitions: not regenerated, its references are not all here")
                status = 1
                continue
            out = Path(tmp) / "transitions" / b
            out.mkdir(parents=True)
            print(f"picks-arrays: transitions of {b} ({len(names)}, {procs} processes)", flush=True)
            rc = run_all([(b, _me("_transitions", b, str(out), str(procs), *names), _env(procs, scratch))], 1)
            want = {f"transitions/{Path(array_paths(b, 'transitions')[n][0]).name}": array_paths(b, "transitions")[n][1]
                    for n in names}
            put, refused = put_matching(want, out, RUN / b)
            status |= _report(f"picks-arrays {b} transitions", put, refused) | (rc[b] != 0)
    return status


def restore_helper(group: str, procs: int, scratch: Path) -> int:
    """The helper's own steps, each in a child process: models (if a model file is missing or wrong), then each body's
    references (the bodies at once), then each body's transitions (``PYTHON_CPU_COUNT`` = procs)."""
    script, files = str(HELPERS[group]), listed(group)
    bad = _bad(files)
    h = helper(group)
    bodies = helper_bodies(group)
    status = 0
    if any(p in bad for b in bodies for p in h.model_paths(b)):
        print(f"{group}: {HELPERS[group].name} models", flush=True)
        status |= run_all([("models", [sys.executable, script, "models"], _env(procs, scratch))], 1)["models"] != 0
    for kind in ("refs", "transitions"):
        todo = [b for b in bodies if any(p in bad and f"/{b}/{kind}/" in p for p in files)]
        if not todo:
            continue
        print(f"{group}: {HELPERS[group].name} arrays BODY {kind} for {', '.join(todo)}", flush=True)
        jobs = [(b, [sys.executable, script, "arrays", b, kind], _env(procs if kind == "transitions" else 1, scratch))
                for b in todo]
        rc = run_all(jobs, procs if kind == "refs" else 1)
        status |= any(rc.values())
    return int(status)


def restore_look(procs: int, scratch: Path) -> int:
    files = listed("look")
    bad = _bad(files)
    if not bad:
        print("look: all here with their listed sha256")
        return 0
    parts = [Path(p).relative_to(LOOK.relative_to(STUDY) / "refs").parts for p in bad]  # body, speed, variant.npz
    bodies, speeds = sorted({x[0] for x in parts}), sorted({x[1] for x in parts})
    variants = sorted({Path(x[2]).stem for x in parts})
    with tempfile.TemporaryDirectory(prefix="restore_look_", dir=scratch) as tmp:
        argv = [sys.executable, "-m", "designlab.stage2.look", "prepare", "--out", tmp, "--procs", str(procs)]
        argv += [a for b in bodies for a in ("--body", b)] + [a for s in speeds for a in ("--speed", s)]
        argv += [a for v in variants for a in ("--variant", v)]
        print(f"look: {len(bad)} rungs: prepare on {', '.join(bodies)} at {', '.join(speeds)} ({len(variants)} "
              f"variants, {procs} processes; about an hour for the whole ladder)", flush=True)
        rc = run_all([("look", argv, _env(procs, scratch))], 1)["look"]
        rel = LOOK.relative_to(STUDY)
        put, refused = put_matching({Path(p).relative_to(rel).as_posix(): s for p, s in bad.items()}, Path(tmp), LOOK)
    return _report("look", put, refused) | (rc != 0)


RESTORE = {"picks-models": restore_picks_models, "picks-arrays": restore_picks_arrays,
           "k": lambda procs, scratch: restore_helper("k", procs, scratch),
           "x": lambda procs, scratch: restore_helper("x", procs, scratch), "look": restore_look}


def git_changes() -> tuple[list[str], list[str]]:
    """(tracked changes, untracked files not ignored) under the study, from ``git status``."""
    st = subprocess.run(["git", "-C", str(STUDY), "status", "--porcelain", "--untracked-files=all", "--", "."],
                        capture_output=True, text=True, check=True).stdout.splitlines()
    return [x for x in st if not x.startswith("??")], [x for x in st if x.startswith("??")]


def restore(groups, procs: int = 2, scratch: str | None = None) -> int:
    """Regenerate every missing or wrong file of ``groups`` (and of the groups their regeneration reads) from the
    committed records, in the order of ``GROUPS``; then ``check`` and ``git status``."""
    scratch_dir = Path(scratch or tempfile.gettempdir()).resolve()
    scratch_dir.mkdir(parents=True, exist_ok=True)
    tracked0, _ = git_changes()
    want = set(groups)
    for g in groups:
        for need in NEEDS.get(g, ()):
            t = tally(listed(need))
            if need not in want and (t["missing"] or t["wrong"]):
                print(f"{g} reads {need} ({TITLES[need]}), which is not all here: restoring it first")
                want.add(need)
    times, status = {}, 0
    for g in GROUPS:
        if g not in want:
            continue
        t0 = time.perf_counter()
        print(f"== {g}: {TITLES[g]}", flush=True)
        rc = RESTORE[g](procs, scratch_dir)
        times[g] = time.perf_counter() - t0
        print(f"== {g}: {'done' if not rc else 'NOT all restored'} in {times[g] / 60:.1f} min", flush=True)
        status |= rc
    print("\ntimes: " + ", ".join(f"{g} {s / 60:.1f} min" for g, s in times.items())
          + f"; total {sum(times.values()) / 60:.1f} min\n")
    status |= check([g for g in GROUPS if g in want])
    tracked, untracked = git_changes()
    new = [x for x in tracked if x not in tracked0]
    if new:
        print("git status: tracked files changed by this run:\n  " + "\n  ".join(new))
        status = 1
    else:
        print("git status: no tracked file changed" + (f" ({len(tracked0)} changed before the run)" if tracked0 else ""))
    if untracked:
        print(f"git status: {len(untracked)} untracked files not ignored: " + ", ".join(untracked[:5]))
    return status


