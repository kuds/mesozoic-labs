def _sha(path: Path) -> str | None:
    try:
        return hashlib.sha256(Path(path).read_bytes()).hexdigest()
    except OSError:
        return None


def _json(path: Path):
    return json.loads(Path(path).read_text())


def _put(src: Path, dest: Path, want: str) -> None:
    """Copy ``src`` to ``dest`` through a temporary name and check it (an interrupted copy leaves no partial file)."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_name(f".part-{dest.name}")  # same suffix: git-ignored like the file
    shutil.copy2(src, tmp)
    if _sha(tmp) != want:
        tmp.unlink()
        raise SystemExit(f"{dest}: the copy's sha256 differs from {want[:8]}")
    os.replace(tmp, dest)


def tally(files: dict[str, str], root: Path | None = None) -> dict[str, list[str]]:
    """The listed files (path -> sha256) under ``root`` (default: this study): here with that sha256 (``ok``),
    ``missing``, or ``wrong``."""
    root = STUDY if root is None else Path(root)
    out: dict[str, list[str]] = dict(ok=[], missing=[], wrong=[])
    for path, want in sorted(files.items()):
        got = _sha(root / path)
        out["missing" if got is None else "ok" if got == want else "wrong"].append(path)
    return out


def put_matching(files: dict[str, str], src_root: Path, dest_root: Path | None = None) -> tuple[list[str], list[str]]:
    """Put each listed file (path -> sha256) of ``src_root`` that has its sha256 in place under ``dest_root`` (default:
    this study), leaving alone one that is already right there; (put, refused), each refusal with its reason."""
    dest_root = STUDY if dest_root is None else Path(dest_root)
    put, refused = [], []
    for path, want in sorted(files.items()):
        if _sha(dest_root / path) == want:
            continue
        got = _sha(src_root / path)
        if got != want:
            refused.append(f"{path}: {'not made' if got is None else f'sha256 {got[:8]}, listed {want[:8]}'}")
            continue
        replaced = (dest_root / path).exists()
        _put(src_root / path, dest_root / path, want)
        put.append(path + (" (replaced a file with another sha256)" if replaced else ""))
    return put, refused


def _study_of(src_dir: str | Path) -> Path:
    """Another checkout's hardware/trex_form_study (``src_dir``: its repository root or the study itself)."""
    src = Path(src_dir).resolve()
    if (src / "hardware" / "trex_form_study").is_dir():
        src = src / "hardware" / "trex_form_study"
    if not (src / "designlab").is_dir():
        raise SystemExit(f"{src_dir}: not a checkout (no hardware/trex_form_study/designlab there)")
    return src


