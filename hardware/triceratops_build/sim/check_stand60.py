"""Four-foot standing check for the 60 cm build models (option C). Rules: PREREG_STAND60.md.

Usage: python check_stand60.py [--out results/stand60_<date>]
Writes results.json and RESULTS.md. Simulation only; nothing here is measured.
The run itself is `check_stand.py`'s (same seeds, perturbation, duration and window), on the 60 cm model files.
"""

import argparse
import json
from pathlib import Path

import mujoco

import check_stand as cs

HERE = Path(__file__).resolve().parent
GEN = HERE / "generated"
CORNERS = cs.CORNERS
# Amendment 1 (changed after a result; PREREG_STAND60.md): revision 2's ledger totals, a regression check (R1); the
# budget's range as a flag (R1b); R5b's references scaled with revision 2's closed mass.
TOTALS = {"listed": 11.540, "closed": 12.694}
BUDGET_RANGE_CLOSED = (11.8, 12.2)
STAND_REF_CLOSED = {"front_flexion": 8.1 * (12.694 / 20.0) * 0.8, "roll": 4.3 * (12.694 / 20.0) * 0.8}
NECK_LIMIT, TAIL_LIMIT = 1.9 / 3, 1.5 / 3


def run(variant, seed):
    """check_stand.run on a 60 cm model: same code path, model file swapped by pointing GEN at a one-file view."""
    orig = cs.GEN
    try:
        cs.GEN = _View(GEN, variant)
        r = cs.run("60cm", variant, seed)
    finally:
        cs.GEN = orig
    r["build"] = "60cm_C"
    return r


class _View:
    """Makes cs.GEN / f"trike_60cm_{variant}.xml" resolve to generated/trike60_C_{variant}.xml."""

    def __init__(self, gen, variant):
        self.gen, self.variant = gen, variant

    def __truediv__(self, name):
        assert name == f"trike_60cm_{self.variant}.xml", name
        return self.gen / f"trike60_C_{self.variant}.xml"


def judge(r, ledger):
    v = r["variant"]
    w = r["weight_n"]
    L = r["foot_load_n"]
    tot = sum(L.values())
    front = (L["left_fore"] + L["right_fore"]) / tot
    left = (L["left_fore"] + L["left_hind"]) / tot
    f = r["actuator_force_nm"]
    out = {}
    out["R1"] = abs(r["mass_kg"] - TOTALS[v]) <= 0.01
    if v == "closed":
        out["R1b_flag_ok"] = BUDGET_RANGE_CLOSED[0] <= r["mass_kg"] <= BUDGET_RANGE_CLOSED[1]
    out["R2"] = (r["min_height_ratio"] >= 0.90 and r["max_tilt_deg"] <= 5.0 and r["finite"]
                 and r["warnings"] == 0 and r["root_speed_rms_mps"] < 0.005)
    out["R3"] = all(x >= 0.10 * w for x in L.values()) and abs(tot - w) <= 0.02 * w
    out["R4a"] = 0.50 <= front <= 0.60
    out["R4c"] = abs(left - 0.50) <= 0.02
    over = [f"{c}_{a}" for c in CORNERS for a in ("roll", "pitch", "flexion")
            if abs(f[f"{c}_{a}"]) > ledger["drives"][f"{c}_{a}"]["joint_thermal_eq_nm"]]
    out["R5a"] = not over
    scale = 1.0 if v == "closed" else TOTALS["listed"] / TOTALS["closed"]
    ff = max(abs(f["left_fore_flexion"]), abs(f["right_fore_flexion"]))
    rr = max(abs(f[f"{c}_roll"]) for c in CORNERS)
    ref_ff, ref_rr = STAND_REF_CLOSED["front_flexion"] * scale, STAND_REF_CLOSED["roll"] * scale
    out["R5b_flag_ok"] = ff <= 1.15 * ref_ff and rr <= 1.15 * ref_rr
    sat = [nm for nm in f if abs(f[nm]) >= 0.99 * r["actuator_limit_nm"][nm]]
    out["R6"] = not sat
    out["R7"] = abs(f["neck_pitch"]) <= NECK_LIMIT and abs(f["tail_pitch"]) <= TAIL_LIMIT
    derived = {"front_share": front, "left_share": left, "foot_sum_over_weight": tot / w,
               "front_flexion_max_nm": ff, "roll_max_nm": rr, "front_flexion_ref_nm": ref_ff, "roll_ref_nm": ref_rr,
               "hind_flexion_max_nm": max(abs(f["left_hind_flexion"]), abs(f["right_hind_flexion"])),
               "pitch_max_nm": max(abs(f[f"{c}_pitch"]) for c in CORNERS),
               "neck_pitch_nm": abs(f["neck_pitch"]), "tail_pitch_nm": abs(f["tail_pitch"]),
               "lever_front_estimate": ledger["front_share_static_estimate"], "over_thermal": over, "saturated": sat}
    return out, derived


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "results" / "stand60_2026-11-18c"))
    out = Path(ap.parse_args().out)
    out.mkdir(parents=True, exist_ok=True)
    results, verdicts = [], {}
    for v in ("listed", "closed"):
        ledger = json.loads((GEN / f"mass_ledger_trike60_C_{v}.json").read_text())
        ok_all = True
        for s in cs.SEEDS:
            r = run(v, s)
            rules, der = judge(r, ledger)
            r["rules"], r["derived"] = rules, der
            results.append(r)
            if s in cs.SEEDS_JUDGED:
                ok_all = ok_all and all(x for k, x in rules.items() if not k.endswith("flag_ok"))
        verdicts[f"60cm_C_{v}"] = "PASS" if ok_all else "FAIL"
    (out / "results.json").write_text(json.dumps({"mujoco": mujoco.__version__, "verdicts": verdicts,
                                                  "runs": results}, indent=1) + "\n")
    lines = ["# Standing check results, 60 cm option C (simulation)", "",
             f"Generated by `check_stand60.py`, mujoco {mujoco.__version__}. Rules: `PREREG_STAND60.md` with amendment 1 "
             "and 2 (model revision 3). Seeds 1 and 2 "
             "are judged; seed 0 is the exact neutral pose. Torques are joint-side, N·m, means over the last 1 s of 10 s.",
             "",
             "| Variant | Seed | Mass kg | Front % | Left % | Feet LF / RF / LH / RH, N | Front elbow | Hind knee | Roll max | Pitch max | Neck | Tail pitch | Rules failed | Flags |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        d, ru, L = r["derived"], r["rules"], r["foot_load_n"]
        failed = [k for k, x in ru.items() if not k.endswith("flag_ok") and not x]
        flags = [k.replace("_flag_ok", "") for k, x in ru.items() if k.endswith("flag_ok") and not x]
        lines.append(f"| {r['variant']} | {r['seed']} | {r['mass_kg']:.3f} | {100 * d['front_share']:.1f} | "
                     f"{100 * d['left_share']:.1f} | {L['left_fore']:.1f} / {L['right_fore']:.1f} / "
                     f"{L['left_hind']:.1f} / {L['right_hind']:.1f} | {d['front_flexion_max_nm']:.2f} "
                     f"(ref {d['front_flexion_ref_nm']:.2f}) | {d['hind_flexion_max_nm']:.2f} | {d['roll_max_nm']:.2f} "
                     f"(ref {d['roll_ref_nm']:.2f}) | {d['pitch_max_nm']:.2f} | {d['neck_pitch_nm']:.3f} | "
                     f"{d['tail_pitch_nm']:.3f} | {', '.join(failed) or 'none'} | {', '.join(flags) or 'none'} |")
    lines += ["", "Verdicts (pre-registered rule set, seeds 1 and 2):", ""]
    lines += [f"- {k}: **{x}**" for k, x in verdicts.items()]
    (out / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
