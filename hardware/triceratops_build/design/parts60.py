"""Write PARTS_60CM.md, the 60 cm (option C) parts list, from its two sources so they cannot drift apart:
- masses and positions: the model generator's mass ledger (sim/generated/mass_ledger_trike60_C_{listed,closed}.json,
  written by sim/build_model60.py), and
- prices: the budget script (budget/size_budget.py, option C with the full expression package and the radio stop).

Planning estimates only: nothing here is quoted, bought, weighed or measured.
Usage: python parts60.py   (writes PARTS_60CM.md next to this file)
"""

import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "budget"))
import size_budget as sb  # noqa: E402

RADIO_STOP_USD = 250   # fail-safe radio stop into the watchdog and Pilz relay (D15; EST, as in size_budget.py)


def family(name):
    n = re.sub(r"^(left|right)_(fore|hind)_", "", name)
    n = re.sub(r"^(left|right)_", "", n)
    n = re.sub(r"_\d+_\d+$", "", n)            # PA11_rib_<ring>_<segment>
    n = re.sub(r"_-?\d+\.\d+_-?1$", "", n)     # tray_stay_<x>_<side>
    n = re.sub(r"_[12]$", "", n)               # gtech_6s_3300_<k>
    return n


def mass_table(ledger):
    fam = OrderedDict()
    for r in ledger["parts"]:
        f = family(r["geom"])
        e = fam.setdefault((r["category"], f), {"n": 0, "kg": 0.0, "pos": [], "basis": r["basis"]})
        e["n"] += 1
        e["kg"] += r["mass_kg"]
        e["pos"].append(r["world_pos_m"])
    rows = []
    for (cat, f), e in sorted(fam.items(), key=lambda kv: (kv[0][0], -kv[1]["kg"])):
        xs = [p[0] for p in e["pos"]]
        zs = [p[2] for p in e["pos"]]
        span = f"{1000 * min(xs):+.0f}" if len(set(round(x, 3) for x in xs)) == 1 else \
            f"{1000 * min(xs):+.0f} to {1000 * max(xs):+.0f}"
        rows.append((cat, f, e["n"], e["kg"], span, 1000 * sum(zs) / len(zs), e["basis"]))
    return rows


def main():
    gen = ROOT / "sim" / "generated"
    led = {v: json.loads((gen / f"mass_ledger_trike60_C_{v}.json").read_text()) for v in ("listed", "closed")}
    cfg = next(c for c in sb.CONFIGS if c[0].startswith("C:"))
    lines = sb.bom(cfg, frame_fixed=0.0)
    servos, expr_usd, _ = sb.expression("full", cfg[1])
    out = ["# Parts list, 60 cm Triceratops (option C)", "",
           "Generated by `design/parts60.py` on the date of its commit. **Planning estimates: nothing here is quoted, "
           "bought, weighed or measured.** Masses and positions come from the simulation model's mass ledger "
           "(`sim/build_model60.py`); prices come from `budget/size_budget.py` (option C, full expression, radio stop), "
           "whose header gives each source tag: PL = the kickoff parts list (`hardware/triceratops_kickoff/"
           "PARTS_PREMIUM.md`, read 7-18 Nov 2026), RC = the repo catalog (maker pages read 7 Nov 2026), WS = web-search "
           "summaries read 18 Nov 2026 (listing pages not opened), EST = estimate.", "",
           "The owner's decisions behind it (`DECISION_LOG.md`): 60 cm option C (D2), full expression (D14), fail-safe "
           "radio stop (D15), budget counted landed and all-in (D12). Open: compute (D3; the Jetson Orin Nano Super is "
           "assumed), chassis and foot (D5; the crawl results argue for a foot that stays flat in roll).", "",
           "## Mass budget", "",
           f"| | Listed | Closed (10 % reserve) |", "|---|---|---|"]
    cats = sorted(set(led["listed"]["category_kg"]) | set(led["closed"]["category_kg"]))
    for c in cats:
        out.append(f"| {c} | {led['listed']['category_kg'].get(c, 0):.3f} kg | "
                   f"{led['closed']['category_kg'].get(c, 0):.3f} kg |")
    out += [f"| **Total** | **{led['listed']['total_mass_kg']:.3f} kg** | **{led['closed']['total_mass_kg']:.3f} kg** |",
            f"| Centre of mass, x (forward of mid-body) | {1000 * led['listed']['com_world_m'][0]:+.1f} mm | "
            f"{1000 * led['closed']['com_world_m'][0]:+.1f} mm |",
            f"| Centre of mass, height | {1000 * led['listed']['com_world_m'][2]:.0f} mm | "
            f"{1000 * led['closed']['com_world_m'][2]:.0f} mm |", "",
            "The closed variant is the one used for the crawl and for training: the 10 % reserve goes first to 0.15 kg of "
            "small parts on the chassis, the rest to pro-rata growth of the frame, shells and harness. The budget's "
            "own estimate for option C was about 11.8 kg (12.2 kg if frame mass scales with area). In simulation the "
            "closed model stands with 55.0 % of its weight on the front feet (`sim/results/stand60_2026-11-18/`).", "",
            "## Parts by mass (closed variant)", "",
            "Position: x along the body (+ forward, from mid-body), height z above the floor, at the neutral standing "
            "pose; a range is given where the parts are spread along the body.", "",
            "| Category | Part | Qty | Mass, total | x, mm | z, mm | Basis |", "|---|---|---|---|---|---|---|"]
    for cat, f, n, kg, span, z, basis in mass_table(led["closed"]):
        out.append(f"| {cat} | {f} | {n} | {kg:.3f} kg | {span} | {z:.0f} | {basis} |")
    out += ["", "## Drives and servos", "", "| Joint | Drive | Ratio | Joint-side limit in the model | Thermal-equilibrium torque at the joint |",
            "|---|---|---|---|---|"]
    seen = set()
    for j, d in led["closed"]["drives"].items():
        key = re.sub(r"^(left|right)_(fore|hind)_", lambda m: m.group(2) + " ", j)
        if key in seen:
            continue
        seen.add(key)
        out.append(f"| {key} | {d['drive']} | {d.get('ratio', 1.0):.1f}:1 | {d['joint_peak_limit_nm']:.2f} N·m | "
                   f"{d.get('joint_thermal_eq_nm', float('nan')):.2f} N·m |" if "joint_thermal_eq_nm" in d else
                   f"| {key} | {d['drive']} | servo | {d['joint_peak_limit_nm']:.2f} N·m | {sb.SERVO[d['drive']][2]:.2f} N·m (one third of stall, EST) |")
    out += ["", "Leg-drive limits are 0.70 × the maker's peak torque (× 0.90 transmission efficiency on the flexion "
            "joints); servo limits are 0.70 × stall at 12 V. Eyelids (XL330-M288-T) and the beak servo are in the model "
            "as mass only; their joints are not modelled yet.", "",
            "## Cost (hardware, before overheads)", "", "| Category | Item | Price | Duty applies |", "|---|---|---|---|"]
    total = 0.0
    for cat, item, usd, duty in lines:
        out.append(f"| {cat} | {item} | ${usd:,.0f} | {'yes' if duty else ''} |")
        total += usd
    out.append(f"| Expression (full) | {', '.join(f'{n}: {x}' for n, x in servos)}; bus adapter, neck bearing and "
               f"spring, eye LEDs, speaker, microphone, frill lighting, 5 V rail | ${expr_usd:,.0f} | |")
    total += expr_usd
    out.append(f"| Safety | fail-safe radio stop into the watchdog and Pilz relay (D15, EST) | ${RADIO_STOP_USD:,} | |")
    total += RADIO_STOP_USD
    out += [f"| **Total** | | **${total:,.0f}** | |", "",
            "This is the budget's chosen build with the frame cost scaled by area (`budget/size_budget_out.txt`, "
            "\"Chosen build\": hardware $16,776; about $20,105 landed from Fremont stock, $22,149 if the drives ship "
            "from the factory). Bench gear and tools are in the total; half the bench gear can be shared with the "
            "T. rex.", "",
            "## Known gaps (to close before ordering)", "",
            "- **The foot.** PR #669's foot (pitch-only passive ankle, sole rigid in roll) fails the crawl at 60 cm as at "
            "75 cm; a passive roll hinge helps but does not pass (`sim/REPORT_60CM.md`). Chassis and foot decision "
            "D5 stays open.",
            "- **Masses are estimates** from PR #669's parts scaled (structure × 0.8^2.5, shells × 0.8^2, head and tail "
            "× 0.8^3) plus catalog masses for bought parts. Weigh the first parts as they arrive.",
            "- **X6 variant.** The US store lists the X6 at 0.78 kg (the X6-50-L); the model uses the X6-60 catalog "
            "mass, 0.82 kg (F9). Question M4 asks which variant ships.",
            "- **TTL servos.** XC430 / XL430 are TTL-bus parts; keep the bus adapter in the head or add an RS-485 "
            "converter for the neck run.",
            "- **Compute** (D3) is assumed, not decided.", ""]
    (HERE / "PARTS_60CM.md").write_text("\n".join(out))
    print(f"wrote PARTS_60CM.md: {len(out)} lines; hardware total ${total:,.0f}")


if __name__ == "__main__":
    main()
